"""Generate the packaged Grove minimum from the platform's dependency pin."""

import argparse
import re
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    # Match the chart's dependency block and fail closed if its layout changes.
    blocks = re.findall(
        r"^  - name: grove-charts\n((?:^(?!  - ).*\n)*)",
        (root / "Chart.yaml").read_text(),
        re.MULTILINE,
    )
    versions = (
        re.findall(r"^    version: (\S+)$", blocks[0], re.MULTILINE)
        if len(blocks) == 1
        else []
    )
    if len(versions) != 1 or not re.fullmatch(
        r"v?\d+\.\d+\.\d+(?:-alpha\.\d+)?", versions[0]
    ):
        parser.error("expected one exact Grove release pin in Chart.yaml")
    output = root / "components/operator/files/grove-preflight/minimum-version.yaml"
    expected = (
        "# SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.\n"
        "# SPDX-License-Identifier: Apache-2.0\n"
        "# Generated by sync_grove_version.py from Chart.yaml; do not edit.\n"
        f"version: {versions[0]}\n"
    )
    if args.check:
        if not output.exists() or output.read_text() != expected:
            parser.exit(1, "Stale Grove minimum; run make sync-grove-version\n")
    else:
        output.write_text(expected)


if __name__ == "__main__":
    main()
