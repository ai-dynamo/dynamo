class UpgradeFixtureLifecycleTest(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.tree = self.root / "fixtures"
        # Exercise the pre-capture boundary even after this PR publishes 1.6 history.
        prefix = fixtures.FIXTURES.relative_to(fixtures.ROOT).as_posix()
        # Generated by generate_upgrade_test_snapshot.py; usable without Git history.
        archive = Path(__file__).parent / "testdata/upgrade-pre-v1.6.0.tar.gz"
        with tarfile.open(archive, "r:gz") as frozen:
            for member in frozen.getmembers():
                if member.isfile():
                    destination = self.tree / Path(member.name).relative_to(prefix)
                    destination.parent.mkdir(parents=True, exist_ok=True)
                    destination.write_bytes(frozen.extractfile(member).read())
        shutil.copyfile(
            fixtures.FIXTURES / "capture-v1.6.0.json", self.tree / "capture-v1.6.0.json"
        )
        inventory = json.loads((self.tree / "capture-v1.6.0.json").read_text())
        self.assertEqual(
            {
                path.relative_to(self.tree).as_posix(): fixtures.digest(path)
                for role in ("history", "latest")
                for path in (self.tree / role).rglob("input.yaml")
            },
            inventory["inputs"],
        )
        chart = self.root / fixtures.CHART
        chart.parent.mkdir(parents=True)
        chart.write_text("appVersion: 1.6.0\n")
        for name, value in (("ROOT", self.root), ("FIXTURES", self.tree)):
            replacement = patch.object(fixtures, name, value)
            replacement.start()
            self.addCleanup(replacement.stop)

    def test_additional_scenario_is_valid_but_incomplete_release_is_blocked(self):
        shutil.copytree(
            self.tree / "latest/sglang-1.5", self.tree / "latest/additional"
        )
        for path in (self.tree / "latest/additional").iterdir():
            path.write_text(
                path.read_text().replace(
                    "upgrade-latest-sglang-1-5", "upgrade-latest-additional"
                )
            )
        fixtures.check()
        before = {
            p.relative_to(self.tree): p.read_bytes()
            for p in self.tree.rglob("*")
            if p.is_file()
        }
        with patch.object(fixtures.subprocess, "run") as capture:
            with self.assertRaisesRegex(ValueError, "Incomplete release matrix"):
                fixtures.regenerate()
            capture.assert_not_called()
        self.assertEqual(
            before,
            {
                p.relative_to(self.tree): p.read_bytes()
                for p in self.tree.rglob("*")
                if p.is_file()
            },
        )

    def test_v160_capture_rejects_scope_drift_and_other_sources(self):
        inventory = fixtures.require_complete_matrix("v1.6.0")
        self.assertEqual(len(inventory["missingScenarios"]), 14)
        for source in (None, "v1.7.0"):
            with (
                self.subTest(source=source),
                self.assertRaisesRegex(ValueError, "Incomplete release matrix"),
            ):
                fixtures.require_complete_matrix(source)
        path = next((self.tree / "latest").rglob("input.yaml"))
        path.write_text(path.read_text() + "\n")
        with self.assertRaisesRegex(ValueError, "frozen v1.6.0 capture inventory"):
            fixtures.require_complete_matrix("v1.6.0")

    def test_v160_capture_advances_every_origin_with_frozen_scope(self):
        inventory = fixtures.require_complete_matrix("v1.6.0")
        source = {
            "sourceKind": "release-tag",
            "sourceRef": "v1.6.0",
            "sourceRevision": inventory["sourceRevision"],
        }
        oldest = self.tree / "history/1.4.0/sglang-1.4/input.yaml"
        predecessor = oldest.read_bytes()
        with (
            patch.object(fixtures, "capture_source", return_value=source),
            patch.object(
                fixtures.subprocess, "run", side_effect=self.capture_api_outputs
            ),
        ):
            fixtures.regenerate(release_tag="v1.6.0")
        fixtures.check()
        self.install_compatibility_fixture()
        fixtures.check()
        lock = json.loads((self.tree / "history.lock.json").read_text())
        self.assertEqual(lock["captureInventory"], inventory)
        self.assertEqual(len(lock["inputs"]), 16)
        self.assertEqual(lock["reconciledVersion"], "1.6.0")
        for legacy in ("sglang-1.4", "sglang-1.5", "sglang-1.5-custom"):
            self.assertFalse((self.tree / "history/1.6.0" / legacy).exists())
        advanced = oldest.read_bytes()
        self.assertNotEqual(advanced, predecessor)
        # A fresh 1.6 origin cannot authorize 1.7 to skip an older origin's 1.6 state.
        (self.root / fixtures.CHART).write_text("appVersion: 1.7.0\n")
        oldest.write_bytes(predecessor)
        with self.assertRaisesRegex(
            ValueError, "Historical input inventory or bytes changed"
        ):
            fixtures.check()
        oldest.write_bytes(advanced)
        with self.assertRaisesRegex(ValueError, "Incomplete release matrix"):
            fixtures.regenerate(release_tag="v1.7.0")
        lock["sourceKind"] = "release-candidate"
        (self.tree / "history.lock.json").write_text(json.dumps(lock))
        with self.assertRaisesRegex(ValueError, "released-tag provenance"):
            fixtures.check()
        lock["sourceKind"] = "release-tag"
        lock["captureInventory"]["missingScenarios"] = []
        (self.tree / "history.lock.json").write_text(json.dumps(lock))
        with self.assertRaisesRegex(ValueError, "frozen scope"):
            fixtures.check()

    def test_regeneration_cannot_skip_a_minor(self):
        (self.root / fixtures.CHART).write_text("appVersion: 1.7.0\n")
        with patch.object(fixtures.subprocess, "run") as capture:
            with self.assertRaisesRegex(
                ValueError, "cannot replay history reconciled by"
            ):
                fixtures.regenerate(release_tag="v1.7.0")
            capture.assert_not_called()

    def capture_api_outputs(self, command, *, env, **kwargs):
        # Model the capture boundary only; production admission/reconciliation is tested by clustertest.
        version = fixtures.app_version((self.root / fixtures.CHART).read_text())
        root = Path(env["DYNAMO_UPGRADE_CAPTURE_DIR"])
        for role in ("history", "compatibility", "latest"):
            for source in fixtures.fixture_inputs(role):
                relative = source.relative_to(self.tree)
                objects = list(yaml.safe_load_all(source.read_text()))
                if role != "latest":
                    for obj in objects:
                        obj["metadata"]["uid"] = "recaptured-uid"
                        if obj["kind"] == "DynamoGraphDeployment":
                            if role == "compatibility" and fixtures.minor(version) > (
                                1,
                                7,
                            ):
                                previous = f"1.{int(version.split('.')[1]) - 1}.0"
                                self.assertEqual(
                                    obj["status"]["conditions"][0]["message"],
                                    f"reconciled by {previous}",
                                )
                            obj.setdefault("status", {})["conditions"] = [
                                {
                                    "type": "Ready",
                                    "status": "False",
                                    "reason": "Captured",
                                    "message": f"reconciled by {version}",
                                }
                            ]
                    destination = root / relative
                    destination.parent.mkdir(parents=True, exist_ok=True)
                    destination.write_text(yaml.safe_dump_all(objects))

                    continue
                for destination in (
                    root / relative,
                    root / "history" / version / Path(*relative.parts[1:]),
                ):
                    namespace = re.sub(
                        r"[^a-z0-9]+",
                        "-",
                        "upgrade-" + destination.parent.relative_to(root).as_posix(),
                    )
                    for obj in objects:
                        obj["metadata"].update(namespace=namespace, uid=namespace)
                        obj["metadata"]["annotations"][
                            "nvidia.com/dynamo-operator-origin-version"
                        ] = version
                    destination.parent.mkdir(parents=True, exist_ok=True)
                    destination.write_text(yaml.safe_dump_all(objects))

    def install_compatibility_fixture(self):
        source = (
            fixtures.OPERATOR
            / "internal/controller/testdata/upgrade/compatibility/missing-origin"
        )
        destination = self.tree / "compatibility/missing-origin"
        shutil.copytree(source, destination)
        lock = json.loads((self.tree / "history.lock.json").read_text())
        self.assertEqual(lock["reconciledVersion"], "1.6.0")
        lock.pop("captureInventory", None)
        path = destination / "input.yaml"
        lock["inputs"] = {path.relative_to(self.tree).as_posix(): fixtures.digest(path)}
        (self.tree / "compatibility.lock.json").write_text(json.dumps(lock))

    def test_complete_matrix_survives_two_release_cycles(self):
        shutil.rmtree(self.tree / "latest")
        matrix = json.loads((self.tree / "required-matrix.json").read_text())[
            "requiredScenarios"
        ]
        for scenario in matrix + ["additional"]:
            path = self.tree / "latest" / scenario / "input.yaml"
            path.parent.mkdir(parents=True)
            path.write_text(
                yaml.safe_dump(
                    {
                        "apiVersion": "nvidia.com/v1beta1",
                        "kind": "DynamoGraphDeployment",
                        "metadata": {
                            "name": "workers",
                            "namespace": "upgrade-latest-" + scenario.replace("/", "-"),
                            "annotations": {
                                "nvidia.com/dynamo-operator-origin-version": "0.0.0"
                            },
                        },
                        "spec": {"image": "runtime:fixed"},
                    }
                )
            )
            fixtures.write_golden(
                path.with_name("output.yaml"),
                [yaml.safe_load(path.read_text())],
                latest=True,
            )

        oldest = self.tree / "history/1.4.0/sglang-1.4/input.yaml"
        original = next(
            obj
            for obj in yaml.safe_load_all(oldest.read_text())
            if obj["kind"] == "DynamoGraphDeployment"
        )
        latest = {
            p.relative_to(self.tree): p.read_bytes()
            for p in (self.tree / "latest").rglob("output.yaml")
        }
        compatibility = self.tree / "compatibility/missing-origin/input.yaml"

        def capture_without_compatibility(command, *, env, **kwargs):
            self.capture_api_outputs(command, env=env, **kwargs)
            (
                Path(env["DYNAMO_UPGRADE_CAPTURE_DIR"])
                / "compatibility/missing-origin/input.yaml"
            ).unlink()

        # Each release consumes the oldest origin's last released-controller state.
        with (
            patch.object(
                fixtures.subprocess, "run", side_effect=self.capture_api_outputs
            ) as capture_command,
            patch.object(
                fixtures,
                "capture_source",
                side_effect=lambda current, *args: {
                    "sourceKind": "release-tag",
                    "sourceRef": f"v{current}",
                    "sourceRevision": "a" * 40,
                },
            ),
        ):
            for version in ("1.6.0", "1.7.0", "1.8.0"):
                with self.subTest(version=version):
                    before = next(
                        obj
                        for obj in yaml.safe_load_all(oldest.read_text())
                        if obj["kind"] == "DynamoGraphDeployment"
                    )
                    if version != "1.6.0":
                        prior_version = f"1.{int(version.split('.')[1]) - 1}.0"
                        self.assertEqual(
                            before["status"]["conditions"][0]["message"],
                            f"reconciled by {prior_version}",
                        )
                        compatibility_before = compatibility.read_bytes()
                        compatibility_lock_before = (
                            self.tree / "compatibility.lock.json"
                        ).read_bytes()
                    (self.root / fixtures.CHART).write_text(f"appVersion: {version}\n")
                    if version == "1.7.0":
                        before_capture = {
                            path.relative_to(self.tree): path.read_bytes()
                            for path in self.tree.rglob("*")
                            if path.is_file()
                        }
                        capture_command.side_effect = capture_without_compatibility
                        with self.assertRaisesRegex(
                            ValueError,
                            "Capture incomplete: compatibility/missing-origin/input.yaml",
                        ):
                            fixtures.regenerate()
                        self.assertEqual(
                            before_capture,
                            {
                                path.relative_to(self.tree): path.read_bytes()
                                for path in self.tree.rglob("*")
                                if path.is_file()
                            },
                        )
                        capture_command.side_effect = self.capture_api_outputs
                    fixtures.regenerate()
                    if version == "1.6.0":
                        fixtures.check()
                        self.install_compatibility_fixture()
                        compatibility_original = next(
                            obj
                            for obj in yaml.safe_load_all(compatibility.read_text())
                            if obj["kind"] == "DynamoGraphDeployment"
                        )
                        provenance = compatibility.with_name("provenance.json")
                        initial_provenance = provenance.read_bytes()
                    else:
                        compatibility_after = compatibility.read_bytes()
                        legacy = next(
                            obj
                            for obj in yaml.safe_load_all(compatibility_after)
                            if obj["kind"] == "DynamoGraphDeployment"
                        )
                        self.assertEqual(legacy["spec"], compatibility_original["spec"])
                        self.assertEqual(
                            legacy["metadata"]["annotations"],
                            compatibility_original["metadata"]["annotations"],
                        )
                        self.assertEqual(
                            legacy["status"]["conditions"][0]["message"],
                            f"reconciled by {version}",
                        )
                        self.assertEqual(provenance.read_bytes(), initial_provenance)

                        # Advancing ordinary history alone cannot authorize the next bump.
                        lock_path = self.tree / "compatibility.lock.json"
                        fresh_lock = lock_path.read_bytes()
                        compatibility.write_bytes(compatibility_before)
                        lock_path.write_bytes(compatibility_lock_before)
                        next_version = f"1.{int(version.split('.')[1]) + 1}.0"
                        (self.root / fixtures.CHART).write_text(
                            f"appVersion: {next_version}\n"
                        )
                        with (
                            patch.object(
                                fixtures.subprocess,
                                "check_output",
                                return_value=f"appVersion: {version}\n",
                            ),
                            self.assertRaisesRegex(ValueError, "same last reconciler"),
                        ):
                            fixtures.check(base="previous-release")
                        compatibility.write_bytes(compatibility_after)
                        lock_path.write_bytes(fresh_lock)
                        (self.root / fixtures.CHART).write_text(
                            f"appVersion: {version}\n"
                        )
                    fixtures.check()
                    after = next(
                        obj
                        for obj in yaml.safe_load_all(oldest.read_text())
                        if obj["kind"] == "DynamoGraphDeployment"
                    )
                    self.assertEqual(
                        after["status"]["conditions"][0]["message"],
                        f"reconciled by {version}",
                    )
                    self.assertEqual(after["spec"], original["spec"])
                    self.assertEqual(
                        after["metadata"]["annotations"],
                        original["metadata"]["annotations"],
                    )
                    with self.assertRaisesRegex(ValueError, "already captured"):
                        fixtures.regenerate()
        self.assertEqual(
            latest,
            {
                p.relative_to(self.tree): p.read_bytes()
                for p in (self.tree / "latest").rglob("output.yaml")
            },
        )
        self.assertFalse((self.tree / "history/1.6.0/additional").exists())
        self.assertFalse((self.tree / "history/1.7.0/additional").exists())
        namespaces = []
        for path in fixtures.fixture_inputs("history") + fixtures.fixture_inputs(
            "latest"
        ):
            namespaces.append(
                next(yaml.safe_load_all(path.read_text()))["metadata"]["namespace"]
            )
        self.assertEqual(len(namespaces), len(set(namespaces)))
        self.assertEqual(
            (self.tree / "RECONCILED_VERSION").read_text().strip(), "1.8.0"
        )
        for path in (self.tree / "latest").rglob("output.yaml"):
            self.assertIn("$var:operator-version", path.read_text())
            self.assertIn("runtime:fixed", path.read_text())
        for path in (self.tree / "history/1.6.0").rglob("input.yaml"):
            self.assertEqual(
                next(yaml.safe_load_all(path.read_text()))["metadata"]["annotations"][
                    "nvidia.com/dynamo-operator-origin-version"
                ],
                "1.6.0",
            )

        # Removing the independent inventory and its lock cannot bypass the gate.
        (self.tree / "compatibility").rename(self.root / "removed-compatibility")
        (self.tree / "compatibility.lock.json").unlink()
        with self.assertRaisesRegex(ValueError, "Missing required missing-origin"):
            fixtures.check()

    def test_candidate_capture_does_not_publish_history(self):
        (self.tree / "required-matrix.json").write_text(
            json.dumps({"requiredScenarios": ["sglang-1.5"]})
        )
        before = {
            p.relative_to(self.tree): p.read_bytes()
            for p in self.tree.rglob("*")
            if p.is_file()
        }
        source = {
            "sourceKind": "release-candidate",
            "sourceRef": "a" * 40,
            "sourceRevision": "a" * 40,
        }
        with (
            patch.object(fixtures, "capture_source", return_value=source),
            patch.object(
                fixtures.subprocess, "run", side_effect=self.capture_api_outputs
            ),
        ):
            output = self.root / "candidate"
            fixtures.regenerate(candidate_sha="a" * 40, candidate_output=output)
        self.assertEqual(
            before,
            {
                p.relative_to(self.tree): p.read_bytes()
                for p in self.tree.rglob("*")
                if p.is_file()
            },
        )
        self.assertEqual(
            json.loads((output / "capture-source.json").read_text())["sourceKind"],
            "release-candidate",
        )
        self.assertTrue((output / "history/1.6.0/sglang-1.5/input.yaml").is_file())

    def test_failed_capture_does_not_publish_history(self):
        (self.tree / "required-matrix.json").write_text(
            json.dumps({"requiredScenarios": ["sglang-1.5"]})
        )
        before = {
            p.relative_to(self.tree): p.read_bytes()
            for p in self.tree.rglob("*")
            if p.is_file()
        }
        with (
            patch.object(fixtures, "capture_source", return_value={}),
            patch.object(
                fixtures.subprocess,
                "run",
                side_effect=subprocess.CalledProcessError(1, "go test"),
            ),
            self.assertRaises(subprocess.CalledProcessError),
        ):
            fixtures.regenerate()
        self.assertEqual(
            before,
            {
                p.relative_to(self.tree): p.read_bytes()
                for p in self.tree.rglob("*")
                if p.is_file()
            },
        )


