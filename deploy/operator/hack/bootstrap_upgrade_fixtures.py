"""One-time 1.5 bootstrap using pinned production admission/controllers (requires PyYAML)."""
import argparse
import copy
import hashlib
import io
import json
import os
import shutil
import subprocess
import tarfile
import tempfile
from pathlib import Path

import yaml

OPERATOR = Path(__file__).resolve().parents[1]
ROOT = OPERATOR.parents[1]
FIXTURES = OPERATOR / "internal/controller/testdata/upgrade"
RELEASES = {
    "1.4.0": "03014943323e78feb5bd672ef08b72caea0918ac",
    "1.5.0": "b83b1d9304ebfc624709ac46db32b1b6f1ff1615",
}
HEADER = "# SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.\n# SPDX-License-Identifier: Apache-2.0\n# Generated by bootstrap_upgrade_fixtures.py; do not edit historical inputs.\n"
SCENARIOS = {
    "sglang-1.4": ("1.4.0", "nvcr.io/nvidia/ai-dynamo/sglang-runtime:1.4.0"),
    "sglang-1.5-custom": (
        "1.4.0",
        "registry.example.com/dynamo/sglang-runtime:v1.5.0-9aa3-repro",
    ),
    "sglang-1.5": ("1.5.0", "nvcr.io/nvidia/ai-dynamo/sglang-runtime:1.5.0"),
}


def dump(path, objects):
    # Field-manager bookkeeping is discarded on replay and is not fixture state.
    objects = copy.deepcopy(objects)
    for obj in objects:
        obj["metadata"].pop("managedFields", None)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER + yaml.safe_dump_all(objects, sort_keys=True))


def bootstrap(destination):
    if destination.exists():
        raise SystemExit("Destination must be a new staging directory")
    destination.mkdir(parents=True)
    provenance = {"reconciledVersion": "1.5.0", "releases": RELEASES, "inputs": {}}
    with tempfile.TemporaryDirectory(prefix="dynamo-upgrade-bootstrap-") as temporary:
        work = Path(temporary)
        for version, sha in RELEASES.items():
            paths = ["deploy/operator", "deploy/helm"]
            if version == "1.4.0":
                paths.append("deploy/snapshot")
            # Fetch only missing official objects; locally rewritten tags are never used.
            if subprocess.run(
                ["git", "cat-file", "-e", sha], cwd=ROOT, capture_output=True
            ).returncode:
                subprocess.run(
                    [
                        "git",
                        "fetch",
                        "--no-tags",
                        "https://github.com/ai-dynamo/dynamo.git",
                        sha,
                    ],
                    cwd=ROOT,
                    check=True,
                )
            data = subprocess.check_output(["git", "archive", sha, *paths], cwd=ROOT)
            checkout = work / version
            checkout.mkdir()
            with tarfile.open(fileobj=io.BytesIO(data)) as archive:
                archive.extractall(checkout, filter="data")
            operator = checkout / "deploy/operator"
            template = (OPERATOR / "hack/upgrade_capture_test.go.tmpl").read_text()
            scale = (
                "scaleClient,err:=env.ScaleClient();require.NoError(t,err);dgdOpts.ScaleClient=scaleClient"
                if version == "1.4.0"
                else ""
            )
            (operator / "internal/controller/zz_capture_upgrade_test.go").write_text(
                template.replace("// SCALE_CLIENT", scale)
            )
            # Same discovery-only observer on both releases; no lowering adapters.
            capture = (
                (OPERATOR / "internal/testing/golden/capture.go")
                .read_text()
                .replace("package golden", "package controller", 1)
            )
            (operator / "internal/controller/zz_capture_owned_test.go").write_text(
                capture
            )
            env = dict(os.environ, GOTOOLCHAIN="go1.26.8")
            info = json.loads(
                subprocess.check_output(
                    [
                        "go",
                        "mod",
                        "download",
                        "-json",
                        "github.com/ai-dynamo/grove/operator/api",
                    ],
                    cwd=operator,
                    env=env,
                )
            )
            shutil.copytree(
                Path(info["Dir"]) / "core/v1alpha1/crds",
                operator / "internal/controller/testing/grove.io",
                dirs_exist_ok=True,
            )
        base = yaml.safe_load((FIXTURES / "scenario.yaml").read_text())
        for scenario, (origin, image) in SCENARIOS.items():
            current = json.loads(json.dumps(base))
            current["metadata"][
                "namespace"
            ] = f"upgrade-{origin.replace('.', '-')}-{scenario.replace('.', '-')}"
            current["metadata"]["name"] = "workers"
            for component in current["spec"]["components"]:
                component["podTemplate"]["spec"]["containers"][0]["image"] = image
            run = work / scenario
            run.mkdir()
            dump(run / "scenario.yaml", [current])
            env = dict(
                os.environ,
                GOTOOLCHAIN="go1.26.8",
                USE_EXISTING_CLUSTER="false",
                UPGRADE_CAPTURE_ROOT=str(run),
                UPGRADE_CAPTURE_VERSION=origin,
                UPGRADE_CAPTURE_INPUT=str(run / "scenario.yaml"),
                UPGRADE_CAPTURE_15_OPERATOR=str(work / "1.5.0/deploy/operator"),
            )
            print(f"Capture {scenario}: origin {origin} -> persisted 1.5", flush=True)
            with (destination / f"{scenario}.log").open("w") as log:
                subprocess.run(
                    [
                        "go",
                        "test",
                        "-p",
                        "2",
                        "./internal/controller",
                        "-run",
                        "^TestCaptureUpgradeBaseline$",
                        "-count=1",
                        "-v",
                        "-timeout",
                        "8m",
                    ],
                    cwd=work / origin / "deploy/operator",
                    env=env,
                    stdout=log,
                    stderr=subprocess.STDOUT,
                    check=True,
                )
            objects = json.loads((run / "1.5.0.json").read_text())
            original = json.loads((run / f"{origin}.json").read_text())
            old_dgd = next(o for o in original if o["kind"] == "DynamoGraphDeployment")
            new_dgd = next(o for o in objects if o["kind"] == "DynamoGraphDeployment")
            hash_key = "nvidia.com/current-worker-hash-v2"
            provenance.setdefault("observations", {})[scenario] = {
                "originVersion": origin,
                "reconciledVersion": "1.5.0",
                "unchangedDGDSpec": old_dgd["spec"] == new_dgd["spec"],
                "oldHash": old_dgd["metadata"]["annotations"].get(hash_key),
                "post15Hash": new_dgd["metadata"]["annotations"].get(hash_key),
            }

            path = destination / "history" / origin / scenario / "input.yaml"
            dump(path, objects)
            provenance["inputs"][str(path.relative_to(destination))] = hashlib.sha256(
                path.read_bytes()
            ).hexdigest()
            if (run / "1.5.log").exists():
                shutil.copyfile(run / "1.5.log", destination / f"{scenario}-1.5.log")
            current["metadata"][
                "namespace"
            ] = f"upgrade-latest-{scenario.replace('.', '-')}"
            # CREATE admission must replace a caller-supplied origin annotation.
            current["metadata"]["annotations"] = {
                "nvidia.com/dynamo-operator-origin-version": "0.0.0"
            }
            dump(destination / "latest" / scenario / "input.yaml", [current])
    for name in [
        "hack/bootstrap_upgrade_fixtures.py",
        "hack/upgrade_capture_test.go.tmpl",
        "internal/testing/golden/capture.go",
        "internal/controller/testdata/upgrade/scenario.yaml",
    ]:
        provenance.setdefault("captureSources", {})[name] = hashlib.sha256(
            (OPERATOR / name).read_bytes()
        ).hexdigest()
    (destination / "bootstrap.json").write_text(
        json.dumps(provenance, indent=2, sort_keys=True) + "\n"
    )
    (destination / "RECONCILED_VERSION").write_text("1.5.0\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    bootstrap(parser.parse_args().output.resolve())
