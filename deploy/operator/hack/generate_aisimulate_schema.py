"""Export the pinned public AISimulate recommendation schema for Go admission.

Set ``AISIMULATE_SOURCE_DIR`` to a checkout of the release's exact AISim source
pin before running ``make generate-aisimulate-schema``. ``--check`` compares a
fresh export without writing. Historical snapshots are retained across pin changes.
"""

from __future__ import annotations

import argparse
import difflib
import importlib.metadata
import json
import os
import re
import subprocess
import sys
import tomllib
from pathlib import Path


def generated_files(root: Path, source: Path) -> dict[Path, str]:
    """Return deterministic exports from the repository-pinned source revision."""
    requirements = root / "container/deps/requirements.aisimulate.txt"
    pins = re.findall(
        r"^aisim==([a-zA-Z0-9.+-]+)\s*$", requirements.read_text(), re.MULTILINE
    )
    if len(pins) != 1:
        raise ValueError(f"{requirements} must contain exactly one aisim== pin")
    pinned = pins[0]
    project = tomllib.loads((root / "pyproject.toml").read_text())
    python_pins = [
        dependency.split(";", 1)[0].strip()
        for dependency in project["project"]["dependencies"]
        if re.match(r"^aisim\b", dependency)
    ]
    if python_pins != [f"aisim=={pinned}"]:
        raise ValueError(
            "pyproject.toml and requirements.aisimulate.txt must pin the same AISimulate version"
        )

    # RC builds share a Python version; the Rust source revision identifies the schema.
    cargo = tomllib.loads((root / "Cargo.toml").read_text())
    patch = cargo["patch"]["crates-io"]["aisim-core"]
    repository = patch["git"]
    revision = patch["rev"]
    if repository != "https://github.com/ai-dynamo/aisimulate.git" or not re.fullmatch(
        r"[0-9a-f]{40}", revision
    ):
        raise ValueError(
            "AISim source pin must use the canonical repository and a full SHA"
        )
    bindings = tomllib.loads((root / "lib/bindings/python/Cargo.toml").read_text())
    if bindings["patch"]["crates-io"]["aisim-core"] != patch:
        raise ValueError("workspace and Python bindings must pin the same AISim source")
    actual_revision = subprocess.check_output(
        ["git", "-C", str(source), "rev-parse", "HEAD"], text=True
    ).strip()
    dirty = subprocess.check_output(
        ["git", "-C", str(source), "status", "--porcelain"], text=True
    ).strip()
    if actual_revision != revision or dirty:
        raise ValueError(f"AISim source must be a clean checkout of {revision}")
    source_project = source / "python/aisimulate"
    metadata = tomllib.loads((source_project / "pyproject.toml").read_text())["project"]
    if metadata["name"] != "aisim" or metadata["version"] != pinned:
        raise ValueError(f"AISim source must publish aisim=={pinned}")

    # Import only after verifying the source; no installed wheel may select another RC.
    sys.path.insert(0, str(source_project / "src"))
    from aisimulate.config import CoreRecommendationConfig

    # Match the public CLI envelope; Python-only validators remain runtime-owned.
    schema = CoreRecommendationConfig.model_json_schema(mode="validation")
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["$comment"] = (
        "Code generated by hack/generate_aisimulate_schema.py; DO NOT EDIT. "
        f"AISim {pinned} from {revision}; Pydantic {importlib.metadata.version('pydantic')}. "
        "Python model validators are not represented by JSON Schema."
    )

    # The CLI splits installed adapter sections before validating the core envelope.
    entry_points = project["project"]["entry-points"]
    sections = {
        name.removeprefix("dynamo.")
        for name in entry_points.get("aisimulate.config_adapters", {})
        if name.startswith("dynamo.")
    }
    if "dgdr_run" not in entry_points.get("aisimulate.output_adapters", {}):
        raise ValueError(
            "the operator's selected dgdr_run output adapter is not registered"
        )
    sections.add("dgdr_run")
    for section in sorted(sections):
        if not section or "." in section or section in schema["properties"]:
            raise ValueError(
                f"adapter section {section!r} is invalid or collides with a core section"
            )
        schema["properties"][section] = {
            "description": "Adapter-owned configuration; validated by the installed runtime adapter.",
            "type": "object",
        }

    output = root / "deploy/operator/internal/aisimulate"
    schema_text = (
        json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    )
    return {
        output / "schemas" / "latest.json": schema_text,
        output / "schemas" / f"{pinned}-{revision}.json": schema_text,
        output
        / "schema_version.go": (
            "// SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.\n"
            "// SPDX-License-Identifier: Apache-2.0\n\n"
            "// Code generated by hack/generate_aisimulate_schema.py; DO NOT EDIT.\n\n"
            "package aisimulate\n\n"
            "// SchemaVersion is the AISimulate version pinned by this operator release.\n"
            f'const SchemaVersion = "{pinned}"\n'
        ),
    }


def generate(root: Path, source: Path, *, check: bool) -> bool:
    """Write the current snapshot, or report every missing or stale export."""
    matches = True
    for path, expected in generated_files(root, source).items():
        if check:
            actual = path.read_text() if path.exists() else ""
            if actual != expected:
                matches = False
                relative = path.relative_to(root)
                print(
                    f"AISimulate schema export is missing or stale: {relative}",
                    file=sys.stderr,
                )
                sys.stderr.writelines(
                    difflib.unified_diff(
                        actual.splitlines(keepends=True),
                        expected.splitlines(keepends=True),
                        fromfile=str(relative),
                        tofile=f"{relative} (regenerated)",
                    )
                )
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
            print(f"Generated {path.relative_to(root)}")
    if not matches:
        print(
            "Run make -C deploy/operator generate-aisimulate-schema and commit the generated exports.",
            file=sys.stderr,
        )
    return matches


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when the pinned schema export is missing or stale",
    )
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[3]
    try:
        source_dir = os.environ.get("AISIMULATE_SOURCE_DIR")
        if not source_dir:
            raise ValueError("set AISIMULATE_SOURCE_DIR to the pinned AISim checkout")
        return 0 if generate(root, Path(source_dir).resolve(), check=args.check) else 1
    except (ImportError, OSError, subprocess.CalledProcessError, ValueError) as exc:
        print(f"AISimulate schema export failed: {exc}", file=sys.stderr)
        print(
            "Provide the exact pinned AISim source and install the operator check dependencies before exporting.",
            file=sys.stderr,
        )
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
