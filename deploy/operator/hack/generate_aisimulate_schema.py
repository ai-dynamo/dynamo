"""Export the pinned public AISimulate recommendation schema for Go admission.

Run ``make generate-aisimulate-schema`` after updating both AISimulate pins and
installing that exact wheel. ``--check`` compares a fresh export without writing.
Historical version snapshots are retained when the active pin changes.
"""

from __future__ import annotations

import argparse
import difflib
import importlib.metadata
import json
import re
import sys
import tomllib
from pathlib import Path


def generated_files(root: Path) -> dict[Path, str]:
    """Return deterministic exports for the installed, repository-pinned version."""
    requirements = root / "container/deps/requirements.aisimulate.txt"
    pins = re.findall(
        r"^aisimulate==([a-zA-Z0-9.+-]+)\s*$", requirements.read_text(), re.MULTILINE
    )
    if len(pins) != 1:
        raise ValueError(f"{requirements} must contain exactly one aisimulate== pin")
    pinned = pins[0]
    project = tomllib.loads((root / "pyproject.toml").read_text())
    python_pins = [
        dependency.split(";", 1)[0].strip()
        for dependency in project["project"]["dependencies"]
        if re.match(r"^aisimulate\b", dependency)
    ]
    if python_pins != [f"aisimulate=={pinned}"]:
        raise ValueError(
            "pyproject.toml and requirements.aisimulate.txt must pin the same AISimulate version"
        )
    installed = importlib.metadata.version("aisimulate")
    if installed != pinned:
        raise ValueError(
            f"installed AISimulate {installed} differs from the repository pin {pinned}"
        )

    # Match the public CLI envelope; Python-only validators remain runtime-owned.
    from aisimulate.config import CoreRecommendationConfig

    schema = CoreRecommendationConfig.model_json_schema(mode="validation")
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["$comment"] = (
        "Code generated by hack/generate_aisimulate_schema.py; DO NOT EDIT. "
        f"AISimulate {pinned}; Pydantic {importlib.metadata.version('pydantic')}. "
        "Python model validators are not represented by JSON Schema."
    )

    # The CLI splits installed adapter sections before validating the core envelope.
    entry_points = project["project"]["entry-points"]
    sections = {
        name.removeprefix("dynamo.")
        for name in entry_points.get("aisimulate.config_adapters", {})
        if name.startswith("dynamo.")
    }
    if "dgdr_run" not in entry_points.get("aisimulate.output_adapters", {}):
        raise ValueError(
            "the operator's selected dgdr_run output adapter is not registered"
        )
    sections.add("dgdr_run")
    for section in sorted(sections):
        if not section or "." in section or section in schema["properties"]:
            raise ValueError(
                f"adapter section {section!r} is invalid or collides with a core section"
            )
        schema["properties"][section] = {
            "description": "Adapter-owned configuration; validated by the installed runtime adapter.",
            "type": "object",
        }

    output = root / "deploy/operator/internal/aisimulate"
    schema_text = (
        json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    )
    return {
        output / "schemas" / f"{pinned}.json": schema_text,
        output
        / "schema_version.go": (
            "// SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.\n"
            "// SPDX-License-Identifier: Apache-2.0\n\n"
            "// Code generated by hack/generate_aisimulate_schema.py; DO NOT EDIT.\n\n"
            "package aisimulate\n\n"
            "// SchemaVersion is the AISimulate version pinned by this operator release.\n"
            f'const SchemaVersion = "{pinned}"\n'
        ),
    }


def generate(root: Path, *, check: bool) -> bool:
    """Write the current snapshot, or report every missing or stale export."""
    matches = True
    for path, expected in generated_files(root).items():
        if check:
            actual = path.read_text() if path.exists() else ""
            if actual != expected:
                matches = False
                relative = path.relative_to(root)
                print(
                    f"AISimulate schema export is missing or stale: {relative}",
                    file=sys.stderr,
                )
                sys.stderr.writelines(
                    difflib.unified_diff(
                        actual.splitlines(keepends=True),
                        expected.splitlines(keepends=True),
                        fromfile=str(relative),
                        tofile=f"{relative} (regenerated)",
                    )
                )
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
            print(f"Generated {path.relative_to(root)}")
    if not matches:
        print(
            "Run make -C deploy/operator generate-aisimulate-schema and commit the generated exports.",
            file=sys.stderr,
        )
    return matches


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when the pinned schema export is missing or stale",
    )
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[3]
    try:
        return 0 if generate(root, check=args.check) else 1
    except (ImportError, importlib.metadata.PackageNotFoundError, ValueError) as exc:
        print(f"AISimulate schema export failed: {exc}", file=sys.stderr)
        print(
            "Install the exact pinned AISimulate wheel and the operator check dependencies before exporting.",
            file=sys.stderr,
        )
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
