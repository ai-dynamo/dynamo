"""Write OTel request spans as NVTXT and import them into Nsight reports.

The Nsight bundle keeps each target's native report and adds the request flow
as NVTX ranges with Nsight Systems' ImportNvtxt, for the multi-report view.
Times use NVTXT's Manual time base, the report's own clock: its session start
is TARGET_INFO_SESSION_START_TIME.utcEpochNs in Unix time and
ANALYSIS_DETAILS.startTime on the report clock. (Relative time cannot express
spans that began before the session, such as long requests already running.)
"""

import os
import re
import shutil
import sqlite3
import subprocess
from contextlib import closing
from pathlib import Path

PROCESS_ID = 900001  # synthetic process in each report: "Dynamo requests"
CONTROL_THREAD = 1  # recording window and control events


def quoted(text: str) -> str:
    # NVTXT strings are quoted and cannot contain newlines.
    return '"' + str(text).replace('"', "'").replace("\n", " ") + '"'


def report_clock(sqlite_path: Path) -> tuple[int, int]:
    """(Unix ns, report-clock ns) of the report's session start."""
    with closing(sqlite3.connect(f"{sqlite_path.as_uri()}?mode=ro", uri=True)) as db:
        utc, clock = db.execute(
            "SELECT utcEpochNs, systemClockNs FROM TARGET_INFO_SESSION_START_TIME"
        ).fetchone()
        tables = {row[0] for row in db.execute("SELECT name FROM sqlite_master")}
        if "ANALYSIS_DETAILS" in tables:
            (clock,) = db.execute("SELECT startTime FROM ANALYSIS_DETAILS").fetchone()
    return utc, clock


def render(threads: dict[int, str], ranges: list, marks: list) -> str:
    """NVTXT text: threads {tid: name}, ranges [(start, end, tid, message)],
    marks [(time, tid, message)], all in report-clock nanoseconds."""
    lines = [
        "# Dynamo request lifecycle spans (OTel), generated by dynamo.profiling.bundle",
        "TimeBase = Manual",
        f"ProcessId = {PROCESS_ID}",
        f"NameProcess, {PROCESS_ID}, {quoted('Dynamo requests')}",
    ]
    lines += [
        f"NameOsThread, {PROCESS_ID}, {tid}, {quoted(name)}"
        for tid, name in sorted(threads.items())
    ]
    lines.append("@RangeStartEnd, Start, End, ThreadId, Message")
    lines += [
        f"RangeStartEnd, {start}, {max(end, start)}, {tid}, {quoted(message)}"
        for start, end, tid, message in sorted(ranges)
    ]
    lines.append("@Marker, Time, ThreadId, Message")
    lines += [
        f"Marker, {t}, {tid}, {quoted(message)}" for t, tid, message in sorted(marks)
    ]
    return "\n".join(lines) + "\n"


def find_importer(explicit: str | None = None) -> str | None:
    """ImportNvtxt from --import-nvtxt, $NSYS_IMPORT_NVTXT, PATH, or next to nsys."""
    for candidate in (
        explicit,
        os.environ.get("NSYS_IMPORT_NVTXT"),
        shutil.which("ImportNvtxt"),
    ):
        if candidate and Path(candidate).is_file():
            return str(candidate)
    nsys = shutil.which("nsys")
    if nsys:
        # <install>/target-*/nsys and <install>/host-*/ImportNvtxt
        found = sorted(Path(nsys).resolve().parents[1].glob("host-*/ImportNvtxt"))
        if found:
            return str(found[0])
    return None


def merge(importer: str, report: Path, nvtxt: Path, output: Path) -> int:
    """Import NVTXT into a copy of the report; returns the imported event count."""
    result = subprocess.run(
        [
            importer,
            "--cmd",
            "merge",
            "-i",
            str(report),
            "-n",
            str(nvtxt),
            "-o",
            str(output),
            "--update_report_time",
        ],
        capture_output=True,
        text=True,
        timeout=600,
    )
    imported = re.search(r"(\d+) events imported", result.stdout + result.stderr)
    if result.returncode or not output.is_file() or not imported:
        raise RuntimeError(
            f"ImportNvtxt failed ({result.returncode}): {(result.stderr or result.stdout)[-500:]}"
        )
    return int(imported.group(1))
