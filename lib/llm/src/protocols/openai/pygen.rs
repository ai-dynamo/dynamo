/// Four spaces, one Python indentation level.
const INDENT: &str = "    ";

/// Marker that names the generator and tells a reader not to edit the file.
pub const GENERATED_MARKER: &str = "# generated by generate-media-protocols; do not edit";

/// Command that regenerates the Python modules.
pub const REGENERATE_COMMAND: &str = "cargo run -p dynamo-llm --bin generate-media-protocols";

/// One generated Python module.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Modality {
    Audio,
    Image,
    Video,
}

impl Modality {
    /// Every modality, in the order the generator writes them.
    pub const ALL: [Modality; 3] = [Modality::Audio, Modality::Image, Modality::Video];

    /// File name of the generated module under
    /// `components/src/dynamo/common/protocols/`.
    pub fn python_file_name(self) -> &'static str {
        match self {
            Modality::Audio => "audio_protocol.py",
            Modality::Image => "image_protocol.py",
            Modality::Video => "video_protocol.py",
        }
    }

    fn module_doc(self) -> &'static str {
        match self {
            Modality::Audio => {
                "Protocol types for audio generation (TTS).\n\n\
                 Generated from the Rust types in lib/llm/src/protocols/openai/audios.rs."
            }
            Modality::Image => {
                "Protocol types for image generation.\n\n\
                 Generated from the Rust types in lib/llm/src/protocols/openai/images.rs."
            }
            Modality::Video => {
                "Protocol types for video generation.\n\n\
                 Generated from the Rust types in lib/llm/src/protocols/openai/videos.rs."
            }
        }
    }

    /// The classes of the module, in output order.
    fn classes(self) -> Vec<ClassSource> {
        match self {
            Modality::Audio => vec![
                ClassSource::of::<audios::NvExt>(ClassKind::Plain),
                ClassSource::of::<audios::NvCreateAudioSpeechRequest>(ClassKind::Request),
                ClassSource::of::<audios::AudioData>(ClassKind::Plain),
                ClassSource::of::<audios::NvAudioSpeechResponse>(ClassKind::Plain),
            ],
            Modality::Image => vec![
                ClassSource::of::<images::NvExt>(ClassKind::Plain),
                ClassSource::of::<images::schema::NvCreateImageRequestSchema>(ClassKind::Request),
                ClassSource::of::<images::schema::ImageData>(ClassKind::Plain),
                ClassSource::of::<images::schema::NvImagesResponseSchema>(ClassKind::Plain),
            ],
            Modality::Video => vec![
                ClassSource::of::<videos::NvExt>(ClassKind::Plain),
                ClassSource::of::<videos::NvCreateVideoRequest>(ClassKind::Request),
                ClassSource::of::<videos::VideoData>(ClassKind::Plain),
                ClassSource::of::<videos::NvVideosResponse>(ClassKind::Plain),
            ],
        }
    }
}

/// Whether a class gets the worker-boundary `extra_args` field.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum ClassKind {
    /// A request class. The frontend adds `extra_args` before dispatch.
    /// Serde skips the field on input, so the schema omits it.
    Request,
    /// Any other class.
    Plain,
}

/// One class to render, with the components its fields reference.
struct ClassSource {
    name: String,
    schema: RefOr<Schema>,
    kind: ClassKind,
    components: Vec<(String, RefOr<Schema>)>,
}

impl ClassSource {
    fn of<T: ToSchema>(kind: ClassKind) -> Self {
        let mut components = Vec::new();
        T::schemas(&mut components);
        Self {
            name: T::name().into_owned(),
            schema: T::schema(),
            kind,
            components,
        }
    }
}

/// Which names the module imports. Only the names the body uses appear.
#[derive(Debug, Default)]
struct Imports {
    any: bool,
    literal: bool,
    optional: bool,
    field: bool,
}

impl Imports {
    fn render(&self) -> String {
        let mut typing = Vec::new();
        if self.any {
            typing.push("Any");
        }
        if self.literal {
            typing.push("Literal");
        }
        if self.optional {
            typing.push("Optional");
        }
        let mut out = String::new();
        if !typing.is_empty() {
            out.push_str(&format!("from typing import {}\n\n", typing.join(", ")));
        }
        out.push_str("from pydantic import BaseModel");
        if self.field {
            out.push_str(", Field");
        }
        out.push('\n');
        out
    }
}

/// A Python type expression and whether the schema allows `null`.
struct PyType {
    expr: String,
    nullable: bool,
}

/// The facts of one field that reach the Python line besides its type.
#[derive(Default)]
struct FieldMeta {
    description: Option<String>,
    default: Option<serde_json::Value>,
    minimum: Option<Number>,
    maximum: Option<Number>,
}

impl FieldMeta {
    fn of(schema: &RefOr<Schema>) -> Self {
        match schema {
            RefOr::Ref(reference) => Self {
                description: non_empty(&reference.description),
                ..Self::default()
            },
            RefOr::T(Schema::Object(object)) => Self {
                description: object.description.clone(),
                default: object.default.clone(),
                minimum: object.minimum.clone(),
                maximum: object.maximum.clone(),
            },
            RefOr::T(Schema::Array(array)) => Self {
                description: array.description.clone(),
                default: array.default.clone(),
                ..Self::default()
            },
            RefOr::T(Schema::OneOf(one_of)) => Self {
                // A nullable reference carries the field description on the
                // referenced item, not on the wrapper.
                description: one_of.description.clone().or_else(|| {
                    one_of
                        .items
                        .iter()
                        .filter(|item| !is_null(item))
                        .find_map(|item| FieldMeta::of(item).description)
                }),
                default: one_of.default.clone(),
                ..Self::default()
            },
            RefOr::T(Schema::AllOf(all_of)) => Self {
                description: all_of.description.clone(),
                default: all_of.default.clone(),
                ..Self::default()
            },
            RefOr::T(_) => Self::default(),
        }
    }
}

/// Renders the Python module of one modality.
pub fn render_module(modality: Modality) -> String {
    render(modality.module_doc(), &modality.classes())
}

/// Directory of the generated Python modules, relative to this crate.
pub fn protocols_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../components/src/dynamo/common/protocols")
}

/// A committed module that differs from the generated text.
#[derive(Debug)]
pub struct Drift {
    pub path: PathBuf,
    pub line: usize,
    pub expected: String,
    pub found: String,
}

impl fmt::Display for Drift {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "{} is out of sync with the Rust types at line {}.\n  \
             expected (from generator): {:?}\n  \
             found    (committed file): {:?}\n\
             Regenerate: {REGENERATE_COMMAND}",
            self.path.display(),
            self.line,
            self.expected,
            self.found,
        )
    }
}

/// Compares the committed module of `modality` with the generated text.
/// Returns the first difference, or `None` when the two are equal.
pub fn check_committed(modality: Modality) -> io::Result<Option<Drift>> {
    let path = protocols_dir().join(modality.python_file_name());
    let generated = render_module(modality);
    let committed = std::fs::read_to_string(&path)
        .map_err(|e| io::Error::new(e.kind(), format!("read {}: {e}", path.display())))?;
    let line_of = |text: &str, line: usize| {
        text.lines()
            .nth(line - 1)
            .unwrap_or("<end of file>")
            .to_string()
    };
    Ok(
        first_divergent_line(&generated, &committed).map(|line| Drift {
            path,
            line,
            expected: line_of(&generated, line),
            found: line_of(&committed, line),
        }),
    )
}

/// Returns the 1-based number of the first line where `expected` and
/// `actual` differ, or `None` when they are equal.
pub fn first_divergent_line(expected: &str, actual: &str) -> Option<usize> {
    let (mut expected, mut actual) = (expected.lines(), actual.lines());
    let mut lineno = 0;
    loop {
        lineno += 1;
        match (expected.next(), actual.next()) {
            (None, None) => return None,
            (expected, actual) if expected == actual => continue,
            _ => return Some(lineno),
        }
    }
}

fn render(module_doc: &str, classes: &[ClassSource]) -> String {
    let mut renderer = Renderer::new(classes);
    let bodies: Vec<String> = classes
        .iter()
        .map(|class| renderer.render_class(class))
        .collect();

    let mut out = String::new();
    out.push_str(
        "# SPDX-FileCopyrightText: Copyright (c) 2025-2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.\n",
    );
    out.push_str("# SPDX-License-Identifier: Apache-2.0\n");
    out.push_str("#\n");
    out.push_str(GENERATED_MARKER);
    out.push('\n');
    out.push_str(&format!("# Regenerate: {REGENERATE_COMMAND}\n"));
    out.push('\n');
    out.push_str(&format!("\"\"\"{module_doc}\n\"\"\"\n"));
    out.push('\n');
    out.push_str(&renderer.imports.render());
    for body in bodies {
        out.push_str("\n\n");
        out.push_str(&body);
    }
    out
}

/// Renders the classes of one module and records the imports they need.
struct Renderer<'a> {
    class_names: Vec<&'a str>,
    components: HashMap<&'a str, &'a RefOr<Schema>>,
    imports: Imports,
}

impl<'a> Renderer<'a> {
    fn new(classes: &'a [ClassSource]) -> Self {
        Self {
            class_names: classes.iter().map(|class| class.name.as_str()).collect(),
            components: classes
                .iter()
                .flat_map(|class| class.components.iter())
                .map(|(name, schema)| (name.as_str(), schema))
                .collect(),
            imports: Imports::default(),
        }
    }

    fn render_class(&mut self, class: &ClassSource) -> String {
        let RefOr::T(Schema::Object(object)) = &class.schema else {
            panic!("class {}: the schema is not an object", class.name);
        };
        let mut lines = vec![format!("class {}(BaseModel):", class.name)];
        if let Some(description) = &object.description {
            push_docstring(&mut lines, INDENT, description);
        }
        for (field, schema) in &object.properties {
            let required = object.required.iter().any(|name| name == field);
            lines.push(String::new());
            self.render_field(&mut lines, field, schema, required);
        }
        if class.kind == ClassKind::Request {
            self.imports.any = true;
            self.imports.optional = true;
            lines.push(String::new());
            lines.push(format!(
                "{INDENT}extra_args: Optional[dict[str, Any]] = None"
            ));
            push_docstring(
                &mut lines,
                INDENT,
                "Worker-boundary passthrough. The frontend nests unknown top-level\n\
                 request fields (an OpenAI client's extra_body) under the\n\
                 \"media_passthrough\" key.",
            );
        }
        if lines.len() == 1 {
            lines.push(format!("{INDENT}pass"));
        }
        lines.join("\n") + "\n"
    }

    fn render_field(
        &mut self,
        lines: &mut Vec<String>,
        field: &str,
        schema: &RefOr<Schema>,
        required: bool,
    ) {
        let ty = self.py_type(field, schema);
        let meta = FieldMeta::of(schema);
        // A field with a non-null default is never optional in Python, because
        // the default stands in for an absent value.
        let optional = ty.nullable || (!required && meta.default.is_none());
        let is_float = ty.expr == "float";
        let annotation = if optional {
            self.imports.optional = true;
            format!("Optional[{}]", ty.expr)
        } else {
            ty.expr
        };
        let default = meta.default.as_ref().map(|value| py_literal(field, value));
        let bounded = meta.minimum.is_some() || meta.maximum.is_some();
        let rhs = if bounded {
            self.imports.field = true;
            let mut args = Vec::new();
            match &default {
                Some(default) => args.push(format!("default={default}")),
                None if optional => args.push("default=None".to_string()),
                None => {}
            }
            if let Some(minimum) = &meta.minimum {
                args.push(format!("ge={}", py_number(minimum, is_float)));
            }
            if let Some(maximum) = &meta.maximum {
                args.push(format!("le={}", py_number(maximum, is_float)));
            }
            format!(" = Field({})", args.join(", "))
        } else {
            match default {
                Some(default) => format!(" = {default}"),
                None if optional => " = None".to_string(),
                None => String::new(),
            }
        };
        lines.push(format!("{INDENT}{field}: {annotation}{rhs}"));
        if let Some(description) = &meta.description {
            push_docstring(lines, INDENT, description);
        }
    }

    fn py_type(&mut self, field: &str, schema: &RefOr<Schema>) -> PyType {
        match schema {
            RefOr::Ref(reference) => {
                let name = reference
                    .ref_location
                    .rsplit('/')
                    .next()
                    .unwrap_or(&reference.ref_location);
                let target = self
                    .components
                    .get(name)
                    .unwrap_or_else(|| panic!("field {field}: unknown component {name}"));
                if let RefOr::T(Schema::Object(object)) = target
                    && let Some(values) = &object.enum_values
                {
                    return self.literal(field, values);
                }
                assert!(
                    self.class_names.contains(&name),
                    "field {field}: component {name} is not a class of this module"
                );
                PyType {
                    expr: name.to_string(),
                    nullable: false,
                }
            }
            RefOr::T(Schema::Object(object)) => {
                if let Some(values) = &object.enum_values {
                    return self.literal(field, values);
                }
                let (ty, nullable) = single_type(field, &object.schema_type);
                let expr = match ty {
                    Type::String => "str",
                    Type::Integer => "int",
                    Type::Number => "float",
                    Type::Boolean => "bool",
                    Type::Object => {
                        assert!(
                            object.properties.is_empty(),
                            "field {field}: inline objects with properties are not supported"
                        );
                        self.imports.any = true;
                        "dict[str, Any]"
                    }
                    Type::Array | Type::Null => {
                        panic!("field {field}: object schema typed as an array or null")
                    }
                };
                PyType {
                    expr: expr.to_string(),
                    nullable,
                }
            }
            RefOr::T(Schema::Array(array)) => {
                let ArrayItems::RefOrSchema(items) = &array.items else {
                    panic!("field {field}: arrays without an item schema are not supported");
                };
                let (_, nullable) = single_type(field, &array.schema_type);
                let inner = self.py_type(field, items);
                PyType {
                    expr: format!("list[{}]", inner.expr),
                    nullable,
                }
            }
            RefOr::T(Schema::OneOf(one_of)) => {
                let non_null: Vec<&RefOr<Schema>> =
                    one_of.items.iter().filter(|item| !is_null(item)).collect();
                let [inner] = non_null.as_slice() else {
                    panic!("field {field}: oneOf with several non-null items is not supported");
                };
                let mut inner = self.py_type(field, inner);
                inner.nullable = inner.nullable || non_null.len() != one_of.items.len();
                inner
            }
            RefOr::T(Schema::AllOf(all_of)) => {
                let [inner] = &all_of.items[..] else {
                    panic!("field {field}: allOf with several items is not supported");
                };
                self.py_type(field, inner)
            }
            RefOr::T(_) => panic!("field {field}: unsupported schema shape"),
        }
    }

    fn literal(&mut self, field: &str, values: &[serde_json::Value]) -> PyType {
        self.imports.literal = true;
        let members: Vec<String> = values
            .iter()
            .map(|value| match value {
                serde_json::Value::String(text) => py_string(field, text),
                other => panic!("field {field}: enum value {other} is not a string"),
            })
            .collect();
        PyType {
            expr: format!("Literal[{}]", members.join(", ")),
            nullable: false,
        }
    }
}

fn non_empty(text: &str) -> Option<String> {
    (!text.is_empty()).then(|| text.to_string())
}

/// The one non-null type of a schema and whether `null` is allowed too.
fn single_type<'a>(field: &str, schema_type: &'a SchemaType) -> (&'a Type, bool) {
    match schema_type {
        SchemaType::Type(ty) => (ty, false),
        SchemaType::Array(types) => {
            let non_null: Vec<&Type> = types
                .iter()
                .filter(|ty| !matches!(ty, Type::Null))
                .collect();
            let [ty] = non_null.as_slice() else {
                panic!("field {field}: a type list with several non-null types is not supported");
            };
            (*ty, non_null.len() != types.len())
        }
        SchemaType::AnyValue => panic!("field {field}: untyped values are not supported"),
    }
}

fn is_null(schema: &RefOr<Schema>) -> bool {
    matches!(
        schema,
        RefOr::T(Schema::Object(object)) if matches!(object.schema_type, SchemaType::Type(Type::Null))
    )
}

fn py_literal(field: &str, value: &serde_json::Value) -> String {
    match value {
        serde_json::Value::String(text) => py_string(field, text),
        serde_json::Value::Number(number) => number.to_string(),
        serde_json::Value::Bool(true) => "True".to_string(),
        serde_json::Value::Bool(false) => "False".to_string(),
        serde_json::Value::Null => "None".to_string(),
        serde_json::Value::Array(items) if items.is_empty() => "[]".to_string(),
        other => panic!("field {field}: default {other} is not supported"),
    }
}

fn py_string(field: &str, text: &str) -> String {
    assert!(
        !text.contains(['"', '\\', '\n']),
        "field {field}: string {text:?} needs escaping, which is not supported"
    );
    format!("\"{text}\"")
}

/// Renders a bound. utoipa stores the bound of an unsigned integer as the
/// float `0.0`. A whole float on an integer field renders as an integer.
fn py_number(number: &Number, is_float: bool) -> String {
    match number {
        Number::Int(value) => value.to_string(),
        Number::UInt(value) => value.to_string(),
        Number::Float(value) if !is_float && value.fract() == 0.0 => {
            format!("{}", *value as i64)
        }
        Number::Float(value) => format!("{value:?}"),
    }
}

/// Appends a docstring. A one-line text closes on the same line. A longer
/// text keeps its lines, indented, and closes on the last line. This is how
/// black leaves a docstring it did not write. A text that ends with a quote
/// gets one space before the closing quotes, as black adds.
fn push_docstring(lines: &mut Vec<String>, indent: &str, text: &str) {
    let text = text.trim();
    assert!(
        !text.contains("\"\"\"") && !text.contains('\\'),
        "docstring {text:?} cannot sit between triple quotes"
    );
    let closing = if text.ends_with('"') {
        " \"\"\""
    } else {
        "\"\"\""
    };
    let mut parts = text.lines().map(str::trim_end).peekable();
    let first = parts.next().unwrap_or_default();
    if parts.peek().is_none() {
        lines.push(format!("{indent}\"\"\"{first}{closing}"));
        return;
    }
    lines.push(format!("{indent}\"\"\"{first}"));
    while let Some(line) = parts.next() {
        let indented = if line.is_empty() {
            String::new()
        } else {
            format!("{indent}{line}")
        };
        if parts.peek().is_none() {
            lines.push(format!("{indented}{closing}"));
        } else {
            lines.push(indented);
        }
    }
}

