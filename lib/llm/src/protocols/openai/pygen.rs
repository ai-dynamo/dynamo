//! Pydantic module emitter for the media protocol types.
//!
//! The three Python protocol modules under
//! `components/src/dynamo/common/protocols/` are generated artifacts. This
//! module renders each of them from the `ToSchema` output of the Rust types.
//! The frontend and the workers then parse one definition.
//!
//! Procedure:
//! 1. To change a field, change the Rust type. Then run
//!    `cargo run -p dynamo-llm --bin generate-media-protocols`. Commit the
//!    Rust file and the Python file together. The freshness test fails until
//!    the two agree.
//! 2. To add a class, add it to [`Modality::classes`]. Keep the order of the
//!    Python module: nvext, request, data, response.
//! 3. The emitter maps a fixed schema subset: `string`, `integer`, `number`,
//!    `boolean`, string enums, arrays, free-form objects, references to the
//!    classes of the module, nullable wrappers, `default`, `minimum`,
//!    `maximum`, and `description`. Anything else panics with the field name.
//!    A new Rust construct cannot produce a wrong Python file silently.
//! 4. The output has the layout that black produces. The generated files are
//!    excluded from the pre-commit hooks, so no hook edits them.

