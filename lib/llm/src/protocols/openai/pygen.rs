    #[test]
    fn push_docstring_closes_on_the_last_line() {
        let mut lines = Vec::new();
        push_docstring(&mut lines, INDENT, "One line.");
        assert_eq!(lines, vec![r#"    """One line.""""#]);

        lines.clear();
        push_docstring(&mut lines, INDENT, "First.\n\nThird.");
        assert_eq!(lines, vec![r#"    """First."#, "", r#"    Third.""""#]);

        // Four quotes in a row would end the string one character early.
        lines.clear();
        push_docstring(&mut lines, INDENT, "Say \"hi\"");
        assert_eq!(lines, vec![r#"    """Say "hi" """"#]);
    }

