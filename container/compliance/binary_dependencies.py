"""Attribute installed Rust/Go binaries using their embedded dependency records.

Syft discovers exact versions. Registry source archives supply Rust declarations
and real LICENSE/NOTICE files. Syft's Go enrichment classifies module licenses;
we also preserve upstream module license/notice texts. Unknown licenses, missing
sources and unmatched local modules fail rather than quietly dropping packages.
The scanner and its downloads live only in the licenses stage.
"""

from __future__ import annotations

import argparse
import dataclasses
import email.parser
import hashlib
import io
import json
import logging
import re
import subprocess
import tarfile
import tempfile
import time
import urllib.error
import urllib.parse
import urllib.request
import zipfile
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path, PurePosixPath

from .audit_image_sbom import _is_first_party
from .generators.common import (
    Component,
    load_subtract_keys,
    spdx_license_text,
    write_cyclonedx,
)
from .generators.dpkg import _resolve_license

try:
    import tomllib
except ModuleNotFoundError:  # Python 3.10 lint/test environments
    import tomli as tomllib

log = logging.getLogger(__name__)
_NOTICE = re.compile(
    r"^(?:licen[sc]e|copying|notice|copyright|authors|(?:A?GPL|LGPL|MPL|MIT|Apache|BSD)[-0-9])(?:$|[._-]|[0-9])",
    re.IGNORECASE,
)
_CATALOGERS = {"cargo-auditable-binary-cataloger", "go-module-binary-cataloger"}


def is_notice_file(path: str) -> bool:
    return bool(_NOTICE.match(PurePosixPath(path).name)) and PurePosixPath(
        path
    ).suffix.lower() not in {
        ".go",
        ".rs",
        ".py",
        ".c",
        ".h",
        ".cc",
        ".cpp",
        ".golden",
    }


def fetch(url: str, cache: Path) -> bytes:
    key = hashlib.sha256(url.encode()).hexdigest()
    path = cache / key
    if path.is_file():
        return path.read_bytes()
    for attempt in range(4):
        try:
            req = urllib.request.Request(
                url, headers={"User-Agent": "dynamo-compliance/1.0"}
            )
            with urllib.request.urlopen(req, timeout=120) as response:
                data = response.read()
            with tempfile.NamedTemporaryFile(dir=cache, delete=False) as temp:
                temp.write(data)
                temporary = Path(temp.name)
            temporary.replace(path)
            return data
        except (urllib.error.URLError, TimeoutError):
            if attempt == 3:
                raise
            time.sleep(2**attempt)
    raise AssertionError("unreachable")


def tar_files(data: bytes) -> dict[str, bytes]:
    # Never extract untrusted archive paths onto the filesystem.
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as archive:
        return {
            member.name.split("/", 1)[1]: archive.extractfile(member).read()
            for member in archive.getmembers()
            if member.isfile()
            and "/" in member.name
            and (
                is_notice_file(member.name)
                or member.name.endswith(("/Cargo.toml", "/.cargo_vcs_info.json"))
            )
        }


def notices(files: dict[str, bytes], prefix: str = "") -> str:
    chunks = []
    for name, data in sorted(files.items()):
        if name.startswith(prefix) and is_notice_file(name):
            chunks.append(
                f"--- {name} ---\n\n{data.decode('utf-8', errors='replace').strip()}"
            )
    if not chunks:
        raise ValueError("source archive has no LICENSE/COPYING/NOTICE text")
    return "\n\n".join(chunks)


def escape_go(value: str) -> str:
    return re.sub(r"[A-Z]", lambda match: "!" + match[0].lower(), value)


def go_license_expression(artifact: dict) -> str | None:
    """Use actual module license files, excluding CLI-generated license samples.

    Cobra's source contains AGPL/GPL templates for projects generated by its
    CLI. Their license text is not the license of Cobra's Apache-licensed code.
    Keep raw enrichment evidence, but do not treat .go templates as declarations.
    """
    expressions = set()
    for license_entry in artifact.get("licenses", []):
        for url in license_entry.get("urls", []):
            path = urllib.parse.unquote(url.split("#", 1)[-1])
            if (
                is_notice_file(path)
                and not path.endswith((".go", ".golden"))
                and not {"testdata", "tests", "examples"}.intersection(
                    PurePosixPath(path).parts
                )
                and license_entry.get("spdxExpression")
            ):
                expressions.add(license_entry["spdxExpression"])
    if not expressions:
        return None
    return " AND ".join(f"({x})" if " " in x else x for x in sorted(expressions))


def debian_git_lfs_main(artifact: dict, root: Path) -> Component | None:
    """Identify Debian's unversioned Git LFS main package, never its modules.

    The public SGLang base compiles this main module without a Go version.
    Its installed Debian file record, version and full copyright provide the
    attribution; independent module dependencies still resolve separately.
    """
    if (
        artifact["name"] != "github.com/git-lfs/git-lfs"
        or artifact["version"] != "UNKNOWN"
        or artifact.get("metadata", {}).get("mainModule") != artifact["name"]
    ):
        return None
    locations = artifact.get("locations", [])
    if not locations or any(loc["path"] != "/usr/bin/git-lfs" for loc in locations):
        raise ValueError("unrecognized Git LFS main executable location")
    files = root / "var/lib/dpkg/info/git-lfs.list"
    if not files.is_file() or "/usr/bin/git-lfs" not in files.read_text().splitlines():
        raise ValueError("Git LFS main executable lacks Debian file ownership")
    status = (root / "var/lib/dpkg/status").read_text()
    records = [email.parser.Parser().parsestr(block) for block in status.split("\n\n")]
    packages = [record for record in records if record.get("Package") == "git-lfs"]
    if len(packages) != 1 or packages[0].get("Status") != "install ok installed":
        raise ValueError("Git LFS main executable lacks an installed Debian package")
    version = packages[0]["Version"]
    text = (root / "usr/share/doc/git-lfs/copyright").read_text()
    spdx = _resolve_license("git-lfs", version, root)
    if spdx == "UNKNOWN" or not text.strip():
        raise ValueError("Git LFS Debian license evidence is incomplete")
    return Component(
        "go",
        artifact["name"],
        "UNKNOWN",
        spdx,
        f"pkg:deb/ubuntu/git-lfs@{version}",
        text,
    )


def etcd_binary_version(path: str, root: Path) -> str:
    """Read the release identity from one of Dynamo's copied etcd executables."""
    if path not in {
        "/usr/local/bin/etcd/etcd",
        "/usr/local/bin/etcd/etcdctl",
        "/usr/local/bin/etcd/etcdutl",
    }:
        raise ValueError(f"unrecognized unversioned etcd executable: {path}")
    executable = root / path.lstrip("/")
    argument = "--version" if executable.name == "etcd" else "version"
    result = subprocess.run(
        [str(executable), argument],
        check=True,
        capture_output=True,
        text=True,
        timeout=10,
    )
    match = re.search(
        r"(?im)^(?:etcd Version|etcdctl version|etcdutl version):\s*"
        r"(\d+\.\d+\.\d+(?:[-+.][A-Za-z0-9.-]+)?)\s*$",
        result.stdout,
    )
    if match is None:
        raise ValueError(f"missing etcd release identity: {path}")
    return "v" + match[1]


def collect(
    sbom: dict,
    output: Path,
    cache: Path,
    syft: str,
    subtract: set[tuple[str, str]] | None = None,
    root: Path = Path("/"),
) -> list[Component]:
    artifacts = [
        a
        for a in sbom["artifacts"]
        if a["foundBy"] in _CATALOGERS and not _is_first_party(a["name"])
    ]
    uv_versions = {}
    etcd_versions = {}
    for a in artifacts:
        for loc in a.get("locations", []):
            path = loc["path"]
            if a["name"] == "uv-version":
                uv_versions[path] = a["version"]
            if (
                a["name"]
                in {
                    "go.etcd.io/etcd/server/v3",
                    "go.etcd.io/etcd/etcdctl/v3",
                    "go.etcd.io/etcd/etcdutl/v3",
                }
                and a["version"] != "UNKNOWN"
            ):
                etcd_versions[path] = a["version"]
    # Frontend images need not ship etcd, and a runtime may not ship UV. Local
    # workspace modules still fail below if their exact source cannot resolve.
    unique = {}
    for a in artifacts:
        # This is a synthetic Go main-package name for mooncake's c-shared
        # wrapper, not an independent library. Its transitive Go modules stay.
        if a["name"] == "command-line-arguments":
            paths = [loc["path"] for loc in a.get("locations", [])]
            if not paths or not all(
                path.endswith("/mooncake/libetcd_wrapper.so") for path in paths
            ):
                raise ValueError("unrecognized Go command-line-arguments owner")
            continue
        if subtract and (a["name"], a["version"]) in subtract:
            continue
        key = (a["type"], a["name"], a["version"])
        if key not in unique:
            unique[key] = dict(a)
        else:
            unique[key]["locations"] = unique[key]["locations"] + a.get("locations", [])
    uv_sources = {
        version: tar_files(
            fetch(
                f"https://codeload.github.com/astral-sh/uv/tar.gz/refs/tags/{version}",
                cache,
            )
        )
        for version in sorted(set(uv_versions.values()))
    }
    # License enrichment of exact module identities; do not resolve or upgrade
    # a dependency graph. Separate manifests support multiple installed versions.
    go_licenses = {}
    with tempfile.TemporaryDirectory() as temp:
        enrichment_root = Path(temp)
        for index, a in enumerate(unique.values()):
            if (
                a["type"] != "go-module"
                or a["version"] == "UNKNOWN"
                or a["name"] == "stdlib"
            ):
                continue
            directory = enrichment_root / str(index)
            directory.mkdir()
            (directory / "go.mod").write_text(
                "module compliance.invalid/inventory\n\ngo 1.23\n\n"
                f"require {a['name']} {a['version']}\n"
            )
        target = output / "go-enrichment.syft.json"
        subprocess.run(
            [
                syft,
                f"dir:{enrichment_root}",
                "--override-default-catalogers",
                "go-module-file-cataloger",
                "--enrich",
                "golang",
                "-o",
                f"syft-json={target}",
            ],
            check=True,
        )
        enriched = json.loads(target.read_text())
        for a in enriched["artifacts"]:
            expression = go_license_expression(a)
            if expression:
                go_licenses[(a["name"], a["version"])] = expression

    def resolve(a: dict) -> Component:
        name, version = a["name"], a["version"]
        if a["type"] == "go-module":
            main = debian_git_lfs_main(a, root)
            if main is not None:
                return main
        if a["type"] == "rust-crate":
            if a.get("metadata", {}).get("source") == "local":
                versions = {
                    uv_versions[loc["path"]]
                    for loc in a["locations"]
                    if loc["path"] in uv_versions
                }
                if not versions:
                    raise ValueError(f"unrecognized local Rust component {name}")
                candidates = []
                for uv_version in sorted(versions):
                    files = uv_sources[uv_version]
                    for path, content in files.items():
                        if path.endswith("Cargo.toml"):
                            doc = tomllib.loads(content.decode())
                            pkg = doc.get("package", {})
                            if pkg.get("name") != name:
                                continue
                            workspace = tomllib.loads(files["Cargo.toml"].decode())
                            pkg_version = pkg.get("version")
                            if isinstance(pkg_version, dict):
                                pkg_version = workspace["workspace"]["package"][
                                    "version"
                                ]
                            if pkg_version != version:
                                continue
                            license_id = pkg.get("license")
                            if isinstance(license_id, dict):
                                license_id = workspace["workspace"]["package"][
                                    "license"
                                ]
                            # Preserve root and crate-specific notices; root terms
                            # apply to workspace-inherited license declarations.
                            text = notices(
                                {
                                    k: v
                                    for k, v in files.items()
                                    if "/" not in k
                                    or k.startswith(
                                        str(PurePosixPath(path).parent) + "/"
                                    )
                                }
                            )
                            candidates.append((license_id, text))
                if not candidates or any(not x[0] for x in candidates):
                    raise ValueError(
                        f"no exact UV source metadata for {name}@{version}"
                    )
                spdx = " AND ".join(sorted({x[0] for x in candidates}))
                text = "\n\n".join(dict.fromkeys(x[1] for x in candidates))
                source = f"https://github.com/astral-sh/uv/tree/{min(versions)}"
            else:
                if a.get("metadata", {}).get("source") != "crates.io":
                    raise ValueError(f"unrecognized Rust source for {name}@{version}")
                meta_url = (
                    "https://crates.io/api/v1/crates/"
                    f"{name}/{urllib.parse.quote(version, safe='')}"
                )
                meta = json.loads(fetch(meta_url, cache))["version"]
                source = (
                    f"https://static.crates.io/crates/{name}/{name}-{version}.crate"
                )
                archive = fetch(source, cache)
                if hashlib.sha256(archive).hexdigest() != meta["checksum"]:
                    raise ValueError(f"crate checksum mismatch: {name}@{version}")
                files = tar_files(archive)
                doc = tomllib.loads(files["Cargo.toml"].decode())
                spdx = doc["package"].get("license")
                try:
                    text = notices(files)
                except ValueError:
                    # Some workspace crates omit inherited LICENSE files from
                    # their published archive. Use the recorded source commit,
                    # never the repository's moving default branch.
                    vcs = json.loads(files.get(".cargo_vcs_info.json", b"{}"))
                    repository = (
                        doc["package"].get("repository", "").removesuffix(".git")
                    )
                    if repository.startswith("https://github.com/") and vcs.get(
                        "git", {}
                    ).get("sha1"):
                        commit = vcs["git"]["sha1"]
                        repo_path = repository.removeprefix("https://github.com/")
                        source = (
                            f"https://codeload.github.com/{repo_path}/tar.gz/{commit}"
                        )
                        upstream = tar_files(fetch(source, cache))
                        relative = vcs.get("path_in_vcs", "").rstrip("/")
                        text = notices(
                            {
                                k: v
                                for k, v in upstream.items()
                                if "/" not in k
                                or (relative and k.startswith(relative + "/"))
                            }
                        )
                    else:
                        # Same explicit canonical-text fallback used by the
                        # existing Rust generator; do not invent copyright.
                        canonical = spdx_license_text(spdx)
                        if not canonical:
                            raise ValueError(
                                f"no upstream or canonical license text for {name}"
                            )
                        authors = ", ".join(doc["package"].get("authors", []))
                        text = (
                            "No license file bundled in the verified crate archive.\n"
                            f"Declared authors: {authors}\n"
                            f"Canonical license text follows:\n\n{canonical}"
                        )
            ecosystem = "rust"
        elif name == "stdlib":
            source = f"https://raw.githubusercontent.com/golang/go/{version}/LICENSE"
            text = fetch(source, cache).decode()
            spdx, ecosystem = "BSD-3-Clause", "go"
        else:
            ecosystem = "go"
            if version == "UNKNOWN":
                versions = {
                    etcd_versions[loc["path"]]
                    for loc in a["locations"]
                    if loc["path"] in etcd_versions
                }
                if not versions and name.startswith("go.etcd.io/etcd/"):
                    versions = {
                        etcd_binary_version(loc["path"], root) for loc in a["locations"]
                    }
                if not name.startswith("go.etcd.io/etcd/") or len(versions) != 1:
                    raise ValueError(f"unresolved local Go module {name}")
                version = versions.pop()
                source = f"https://codeload.github.com/etcd-io/etcd/tar.gz/refs/tags/{version}"
                files = tar_files(fetch(source, cache))
                expected = spdx_license_text("Apache-2.0").split("\n\n", 1)[1]
                if files["LICENSE"].decode().split() != expected.split():
                    raise ValueError(
                        "etcd root license changed; review local module terms"
                    )
                text = notices(files)
                spdx = "Apache-2.0"
            else:
                spdx = go_licenses.get((name, version))
                source = (
                    f"https://proxy.golang.org/{escape_go(name)}/@v/"
                    f"{escape_go(version)}.zip"
                )
                data = fetch(source, cache)
                with zipfile.ZipFile(io.BytesIO(data)) as archive:
                    files = {
                        path: archive.read(path)
                        for path in archive.namelist()
                        if not path.endswith("/") and is_notice_file(path)
                    }
                text = notices(files)
        if not spdx or spdx == "UNKNOWN":
            raise ValueError(f"unresolved license: {name}@{version}")
        # Cargo historically accepted '/' for SPDX alternatives.
        spdx = spdx.replace("/", " OR ")
        return Component(ecosystem, name, version, spdx, source, text)

    components = []
    errors = []
    with ThreadPoolExecutor(max_workers=6) as executor:
        tasks = {executor.submit(resolve, a): a for a in unique.values()}
        for task in as_completed(tasks):
            a = tasks[task]
            try:
                components.append(task.result())
            except (
                ValueError,
                KeyError,
                OSError,
                urllib.error.URLError,
                subprocess.SubprocessError,
            ) as error:
                message = f"{a['name']}@{a['version']}: {error}"
                errors.append(message)
                log.error(message)
    if errors:
        raise ValueError("Unresolved binary dependencies:\n" + "\n".join(errors))
    # The same etcd module may appear both with an explicit version and as
    # a local workspace replacement in another binary. Merge notice text before
    # writing so these records cannot race or overwrite one another's terms.
    merged = {}
    for component in components:
        identity = (component.ecosystem, component.name, component.version)
        previous = merged.get(identity)
        if previous is not None:
            if component.spdx != previous.spdx:
                raise ValueError(f"conflicting license metadata for {identity}")
            component = dataclasses.replace(
                component,
                license_text="\n\n".join(
                    dict.fromkeys([previous.license_text, component.license_text])
                ),
            )
        merged[identity] = component
    components = sorted(merged.values(), key=lambda c: (c.ecosystem, c.name, c.version))
    for ecosystem in ("rust", "go"):
        (output / f"{ecosystem}-licenses").mkdir(exist_ok=True)
    for component in components:
        name = (
            escape_go(component.name) if component.ecosystem == "go" else component.name
        )
        key = (
            f"{name}@{component.version}"
            if component.ecosystem == "go"
            else f"{name}-{component.version}"
        )
        if PurePosixPath(key).is_absolute() or ".." in PurePosixPath(key).parts:
            raise ValueError(f"unsafe component key: {key}")
        directory = output / f"{component.ecosystem}-licenses" / key
        directory.mkdir(parents=True, exist_ok=True)
        (directory / "LICENSE-NOTICES.txt").write_text(component.license_text)
        log.info(
            "%s %s %s: %s",
            component.ecosystem,
            component.name,
            component.version,
            component.spdx,
        )
    for ecosystem in ("rust", "go"):
        write_cyclonedx(
            [c for c in components if c.ecosystem == ecosystem],
            output / f"{ecosystem}.cdx.json",
        )
    return components


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--syft-sbom", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--cache", type=Path, required=True)
    parser.add_argument("--syft", default="syft")
    parser.add_argument("--subtract-sbom", type=Path)
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO)
    args.output.mkdir(parents=True, exist_ok=True)
    args.cache.mkdir(parents=True, exist_ok=True)
    subtract = load_subtract_keys(args.subtract_sbom) if args.subtract_sbom else None
    collect(
        json.loads(args.syft_sbom.read_text()),
        args.output,
        args.cache,
        args.syft,
        subtract,
    )


if __name__ == "__main__":
    main()
