import logging
import re
from pathlib import Path

logger = logging.getLogger(__name__)

# SPDX-expression sentinel that means "we don't know what license this is".
# Policy validation treats UNKNOWN as a deny by default (configurable via
# licenses.toml [licenses].unknown).
UNKNOWN = "UNKNOWN"

# Vendored canonical SPDX license texts (one <ID>.txt per allowed identifier,
# sourced from spdx/license-list-data). Used as the license-text source for
# ecosystems whose components ship no bundled LICENSE file in the licenses
# stage (rust, go) — see spdx_license_text().
_SPDX_TEXT_DIR = Path(__file__).resolve().parent.parent / "spdx_licenses"
_SPDX_OPERATORS = frozenset({"AND", "OR", "WITH"})


def _spdx_ids(spdx_expr: str) -> list[str]:
    """Extract the ordered, de-duplicated license/exception IDs in an SPDX
    expression, dropping operators and parentheses.

    "Apache-2.0 WITH LLVM-exception" -> ["Apache-2.0", "LLVM-exception"]
    "MIT OR Apache-2.0"              -> ["MIT", "Apache-2.0"]
    """
    ids: list[str] = []
    for tok in re.split(r"[()\s]+", spdx_expr or ""):
        tok = tok.strip().rstrip("+")  # normalize "Apache-2.0+" -> "Apache-2.0"
        if not tok or tok.upper() in _SPDX_OPERATORS:
            continue
        if tok not in ids:
            ids.append(tok)
    return ids


def read_harvested_license(base_dir: Path | None, key: str) -> str | None:
    """Read + concatenate the upstream LICENSE files harvested for `key`.

    The builder stages (wheel_builder for rust, the go-builders for go) copy
    each dependency's real LICENSE/COPYING/NOTICE files into `base_dir/<key>/`,
    mirroring the source-cache layout (rust: "<name>-<version>"; go: the
    escaped module path "<path>@<version>"). Returns None when base_dir is
    unset or no readable license files exist for the key, so callers fall back
    to canonical SPDX text.
    """
    if base_dir is None:
        return None
    pkg_dir = base_dir / key
    if not pkg_dir.is_dir():
        return None
    texts: list[str] = []
    for f in sorted(pkg_dir.iterdir()):
        if not f.is_file():
            continue
        try:
            body = f.read_text(encoding="utf-8", errors="replace").strip()
        except OSError:
            continue
        if body:
            texts.append(f"--- {f.name} ---\n\n{body}")
    return "\n\n".join(texts) if texts else None


def spdx_license_text(spdx_expr: str) -> str | None:
    """Return the canonical SPDX license text(s) for an SPDX expression, or None.

    Looks up each referenced license/exception ID in the vendored
    spdx_licenses/ store. Compound expressions (e.g. "MIT OR Apache-2.0")
    yield the concatenated texts of every referenced ID, each under a
    `--- <ID> ---` banner. IDs with no vendored text (UNKNOWN, LicenseRef-*,
    or anything outside the policy allow-list) are skipped; returns None when
    nothing resolves so callers fall back to SPDX-identifier-only attribution.
    """
    if not spdx_expr or spdx_expr == UNKNOWN:
        return None
    chunks: list[str] = []
    for lid in _spdx_ids(spdx_expr):
        path = _SPDX_TEXT_DIR / f"{lid}.txt"
        if not path.is_file():
            continue
        try:
            body = path.read_text(encoding="utf-8").rstrip()
        except OSError:
            continue
        chunks.append(f"--- {lid} ---\n\n{body}")
    if not chunks:
        return None
    return "\n\n".join(chunks)


@dataclasses.dataclass(frozen=True)
class Component:
    """One row in the per-ecosystem NOTICES output and *-deps.csv."""

    ecosystem: str  # "rust" | "go" | "python" | "dpkg" | "native"
    name: str
    version: str
    spdx: str  # SPDX expression, possibly compound; UNKNOWN if unresolved
    source_url: str | None = None  # registry URL, where applicable
    license_text: str | None = None  # full LICENSE text, where available
    # True when license_text is the canonical SPDX text (the dependency shipped
    # no license file of its own); render_notices prepends a disclaimer.
    license_text_is_canonical: bool = False


_NOTICES_HEADER = """\
NOTICES — {ecosystem} dependencies
==================================

This file is automatically generated. Do not edit it directly.

It enumerates every {ecosystem} package shipped in this artifact (container
image or wheel), with its SPDX license expression. Where license text is
available — the package's
bundled LICENSE file, or the canonical SPDX text for its identifier — it
appears verbatim under each section; otherwise the SPDX identifier is the
authoritative reference.

"""

# Disclaimer printed above the license body when the text is the canonical
# SPDX text rather than a file the dependency itself distributed.
_CANONICAL_TEXT_NOTE = (
    "No license file was distributed with this package in the image; the "
    "canonical SPDX license text for its declared identifier is reproduced "
    "below for reference. See the Source URL above for the package's "
    "copyright holders."
)


def render_notices(ecosystem: str, components: list[Component]) -> str:
    """Render a NOTICES-<Ecosystem>.txt file body.

    Components are sorted by name (case-insensitive) then version. The same
    component appearing multiple times (different versions) gets one section
    per version.
    """
    sorted_comps = sorted(components, key=lambda c: (c.name.lower(), c.version))

    parts: list[str] = [_NOTICES_HEADER.format(ecosystem=ecosystem)]
    for c in sorted_comps:
        parts.append(f"## {c.name} {c.version}\n\n")
        parts.append(f"License: {c.spdx}\n")
        if c.source_url:
            parts.append(f"Source: {c.source_url}\n")
        if c.license_text:
            if c.license_text_is_canonical:
                parts.append(f"\n{_CANONICAL_TEXT_NOTE}\n")
            parts.append("\n```\n")
            parts.append(c.license_text.rstrip() + "\n")
            parts.append("```\n")
        parts.append("\n")
    return "".join(parts)


def write_notices(
    ecosystem: str, components: list[Component], output_dir: Path
) -> Path:
    """Write NOTICES-<Ecosystem>.txt under output_dir; return its path."""
    output_dir.mkdir(parents=True, exist_ok=True)
    notices_path = output_dir / f"NOTICES-{ecosystem.capitalize()}.txt"
    notices_path.write_text(render_notices(ecosystem, components), encoding="utf-8")
    return notices_path


_THIRD_PARTY_HEADER = """\
THIRD-PARTY SOFTWARE NOTICES
============================

This file is automatically generated. Do not edit it directly.

This file lists the third-party software in this container: first the
software Dynamo adds, then the software of the base image it is built on. Each
entry names the package, its version and its declared licenses. Full license
texts, where available, follow each entry or, for the base image, appear once
at the end of its section. The software Dynamo adds is also listed in
machine-readable form in osrb-deps.csv and osrb.cdx.json next to this file.

"""

_BASE_SECTION_HEADER = """\
BASE IMAGE — {image}
{rule}

The packages below are those of the baseline image above, as recorded in its
SBOM ({sbom}). Everything this container adds on top of that image, including
any intermediate upstream image, is listed in the sections before this one.
{debs}Entries are otherwise listed as the baseline publishes them, so a package
the Dynamo build removes may still appear. Canonical SPDX license texts follow
the list, once per license.

"""

_BASE_DEBS_FILTERED = (
    "Debian packages are limited to those still installed in this image, each "
    "followed by its copyright file where the image ships one. "
)

DEB_COPYRIGHT_DIR = Path("usr/share/doc")


def read_deb_copyright(root: Path, package: str) -> str | None:
    """Return the text of a Debian package's copyright file under root, or None."""
    try:
        return (root / DEB_COPYRIGHT_DIR / package / "copyright").read_text(
            encoding="utf-8", errors="replace"
        )
    except OSError:
        return None


# Debian license names that are exactly an SPDX license. dpkg's wider mapping
# guesses versions (Artistic -> Artistic-2.0, public-domain -> CC0-1.0), which
# would change a baseline's declared terms.
_DEBIAN_EXACT_ALIASES = {"Expat": "MIT"}

# Placeholder for a base-image component whose SBOM entry declares no license.
NOASSERTION = "NOASSERTION"


def _base_image_label(sbom_path: Path) -> str:
    """Return "<image>:<tag>" for a baseline SBOM from manifest.json, else its filename."""
    manifest = sbom_path.parent / "manifest.json"
    try:
        for entry in json.loads(manifest.read_text(encoding="utf-8"))["entries"]:
            if entry.get("baseline_sbom") == sbom_path.name:
                image, tag = entry.get("baseline_image"), entry.get("baseline_tag")
                if image and tag:
                    return f"{image}:{tag}"
    except (OSError, ValueError, LookupError, TypeError, AttributeError):
        pass
    return sbom_path.name


_LICENSE_NAME_FILLER = frozenset({"License", "license", "The", "the"})


def _bare_license_ids(name: str) -> list[str]:
    """Resolve a free-text SBOM license name to SPDX IDs, or keep it whole.

    "MIT License" -> ["MIT"]; a name with any unresolved word, such as
    "Apache-2.0 with LLVM exceptions", stays one unresolved identifier.
    """
    words = [w for w in _spdx_ids(name) if w not in _LICENSE_NAME_FILLER]
    if words and all(spdx_license_text(w) for w in words):
        return words
    return [name]


@dataclasses.dataclass(frozen=True)
class BaseComponent(Component):
    """A baseline SBOM component, with the license IDs parsed from each entry."""

    license_ids: tuple[str, ...] = ()


def _base_license_rank(component: BaseComponent) -> tuple[bool, int, bool]:
    """Prefer a fully resolvable SPDX record, then more resolved identifiers."""
    identifiers = set(component.license_ids)
    resolved = sum(spdx_license_text(lid) is not None for lid in identifiers)
    return (
        bool(identifiers) and resolved == len(identifiers),
        resolved,
        component.spdx != NOASSERTION,
    )


def load_base_components(
    sbom_path: Path,
    shipped_debs: set[tuple[str, str]] | None = None,
    dpkg_root: Path = Path("/"),
    python_components: list[Component] | None = None,
) -> list[BaseComponent]:
    """Return the library and application components of a baseline CycloneDX SBOM.

    Licenses are joined with " AND "; a component with none gets NOASSERTION.
    shipped_debs is the (name, version) set the dpkg generator found in the
    shipped filesystem at dpkg_root: a Debian package outside it is dropped, and
    one inside it gets its /usr/share/doc/<pkg>/copyright file, when present,
    as license text. An empty set means the scan found nothing: no filter.
    python_components supplies bundled licenses collected before subtraction.
    """
    shipped_debs = shipped_debs or None
    # Match the separator-insensitive Python names used by baseline subtraction.
    python_licenses = {
        (re.sub(r"[-_.]+", "-", c.name).lower(), c.version): c.license_text
        for c in python_components or []
        if c.license_text and not c.license_text_is_canonical
    }
    doc = json.loads(sbom_path.read_text(encoding="utf-8"))
    by_key: dict[tuple[str, str], BaseComponent] = {}
    for c in doc.get("components", []) or []:
        name, version = c.get("name"), c.get("version")
        if c.get("type") not in ("library", "application") or not name or not version:
            continue
        version = str(version)
        is_deb = (c.get("purl") or "").startswith("pkg:deb/")
        ids: list[str] = []
        license_ids: list[str] = []
        for entry in c.get("licenses") or []:
            lic = entry.get("license") or {}
            ident = lic.get("id") or lic.get("name") or entry.get("expression")
            # syft names an unidentified license file by its content hash.
            if not ident or ident.startswith("sha256:"):
                continue
            if is_deb and not lic.get("id"):
                ident = _DEBIAN_EXACT_ALIASES.get(ident, ident)
            # Parse each entry on its own, so a stray paren stays inside it.
            if lic.get("id"):
                entry_ids = _spdx_ids(ident)  # "LGPL-3.0+" -> "LGPL-3.0"
            elif re.search(r" (AND|OR|WITH) ", ident):
                entry_ids = _spdx_ids(ident)
                ident = f"({ident})"
            else:
                entry_ids = _bare_license_ids(ident)
            if ident not in ids:
                ids.append(ident)
                license_ids.extend(entry_ids)
        text = None
        if (c.get("purl") or "").startswith("pkg:pypi/"):
            text = python_licenses.get((re.sub(r"[-_.]+", "-", name).lower(), version))
        if shipped_debs is not None and is_deb:
            if (name, version) not in shipped_debs:
                continue
            text = read_deb_copyright(dpkg_root, name)
        comp = BaseComponent(
            ecosystem="base",
            name=name,
            version=version,
            spdx=" AND ".join(ids) if ids else NOASSERTION,
            license_text=text,
            license_ids=tuple(license_ids),
        )
        existing = by_key.get((name, version))
        if existing is None or _base_license_rank(comp) > _base_license_rank(existing):
            by_key[(name, version)] = comp
    return list(by_key.values())


def render_base_section(
    sbom_path: Path, components: list[BaseComponent], debs_note: str = ""
) -> str:
    """Render the base-image section of THIRD-PARTY.txt."""
    image = _base_image_label(sbom_path)
    parts = [
        _BASE_SECTION_HEADER.format(
            image=image,
            rule="=" * len(f"BASE IMAGE — {image}"),
            sbom=sbom_path.name,
            debs=debs_note,
        )
    ]
    license_ids: set[str] = set()
    for c in sorted(components, key=lambda c: (c.name.lower(), c.version)):
        parts.append(f"## {c.name} {c.version}\n\nLicenses: {c.spdx}\n")
        if c.license_text:
            parts.append("\n```\n" + c.license_text.rstrip() + "\n```\n")
        parts.append("\n")
        license_ids.update(c.license_ids)
    license_ids -= {NOASSERTION, UNKNOWN}
    parts.append("# License texts\n\n")
    missing: list[str] = []
    emitted: set[str] = set()
    for lid in sorted(license_ids, key=str.lower):
        text = spdx_license_text(lid) if _spdx_ids(lid) == [lid] else None
        if text is None:
            missing.append(lid)
        elif text not in emitted:
            # "MIT", "MIT License" and "(MIT)" all resolve to the same text.
            emitted.add(text)
            parts.append("```\n" + text.rstrip() + "\n```\n\n")
    if missing:
        parts.append(
            "No canonical text is vendored for the identifiers below; the "
            "identifier, and the package's own copyright file where the image "
            "ships one, is the reference:\n" + "\n".join(missing) + "\n"
        )
    return "".join(parts)


def write_third_party(
    output_dir: Path,
    ecosystems: list[str],
    source_location: str | None = None,
    base_sbom: Path | None = None,
    shipped_debs: set[tuple[str, str]] | None = None,
    dpkg_root: Path = Path("/"),
    python_components: list[Component] | None = None,
) -> Path:
    """Write THIRD-PARTY.txt: this run's NOTICES files plus the base image's components."""
    parts = [_THIRD_PARTY_HEADER]
    if source_location:
        parts.append(
            "Source code for the open-source software in this container is "
            f"available at:\n{source_location}\n\n"
        )
    for eco in sorted(ecosystems):
        notices = output_dir / f"NOTICES-{eco.capitalize()}.txt"
        if notices.is_file():
            parts.append(notices.read_text(encoding="utf-8").rstrip() + "\n\n")
    if base_sbom is not None:
        base = load_base_components(
            base_sbom, shipped_debs, dpkg_root, python_components
        )
        section = render_base_section(
            base_sbom, base, _BASE_DEBS_FILTERED if shipped_debs else ""
        )
        parts.append(section.rstrip() + "\n")
    output_dir.mkdir(parents=True, exist_ok=True)
    path = output_dir / "THIRD-PARTY.txt"
    path.write_text("".join(parts).rstrip() + "\n", encoding="utf-8")
    return path


def write_deps_csv(
    ecosystem: str, components: list[Component], output_dir: Path
) -> Path:
    """Write <ecosystem>-deps.csv for the policy validator. Stable byte-order.

    Columns: ecosystem,name,version,spdx,source_url
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    csv_path = output_dir / f"{ecosystem.lower()}-deps.csv"
    sorted_comps = sorted(components, key=lambda c: (c.name.lower(), c.version))
    with csv_path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(["ecosystem", "name", "version", "spdx", "source_url"])
        for c in sorted_comps:
            writer.writerow(
                [c.ecosystem, c.name, c.version, c.spdx, c.source_url or ""]
            )
    return csv_path


# Map our ecosystem label to the corresponding Package-URL type, used to
# synthesize a purl for the merged CycloneDX SBOM when a component's
# source_url isn't already a purl (python/dpkg/go/native give registry URLs).
_PURL_TYPE = {
    "python": "pypi",
    "rust": "cargo",
    "dpkg": "deb",
    "go": "golang",
    "native": "generic",
}


def _component_purl(c: "Component") -> str | None:
    """Best-effort Package-URL for a component (its own source_url if already a
    purl, else synthesized from ecosystem/name/version)."""
    if c.source_url and c.source_url.startswith("pkg:"):
        return c.source_url
    ptype = _PURL_TYPE.get(c.ecosystem)
    if not ptype or not c.name or not c.version:
        return None
    return f"pkg:{ptype}/{c.name}@{c.version}"


def _cdx_licenses(spdx: str) -> list[dict] | None:
    """CycloneDX `licenses` array for an SPDX expression.

    Single SPDX id -> {license:{id}}; LicenseRef-* / non-SPDX -> {license:{name}};
    compound (AND/OR/WITH) -> {expression}; UNKNOWN/empty -> None (omit).
    """
    if not spdx or spdx == UNKNOWN:
        return None
    if any(f" {op} " in f" {spdx} " for op in _SPDX_OPERATORS):
        return [{"expression": spdx}]
    if spdx.startswith("LicenseRef-"):
        return [{"license": {"name": spdx}}]
    return [{"license": {"id": spdx}}]


def write_merged_csv(
    components: list[Component],
    exception_reasons: dict[tuple[str, str], str],
    output_path: Path,
) -> Path:
    """Write the single cross-ecosystem OSRB deps CSV. Stable byte-order.

    Columns: ecosystem,name,version,spdx,source_url,notes

    `notes` carries the justification for **non-permissive** packages: the
    `reason` from the matching policy `[[exceptions]]` entry, keyed by
    (ecosystem, name). A package only has an exception if its license wasn't
    permissively allowed, so permissive packages get an empty note.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    sorted_comps = sorted(
        components, key=lambda c: (c.ecosystem, c.name.lower(), c.version)
    )
    with output_path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(["ecosystem", "name", "version", "spdx", "source_url", "notes"])
        for c in sorted_comps:
            note = exception_reasons.get((c.ecosystem, c.name), "")
            writer.writerow(
                [c.ecosystem, c.name, c.version, c.spdx, c.source_url or "", note]
            )
    return output_path


def write_cyclonedx(components: list[Component], output_path: Path) -> Path:
    """Write a CycloneDX 1.5 SBOM of the (baseline-subtracted delta) components.

    This is the same component set as the merged CSV and NOTICES — only what
    the image adds above its baseline, never the full image. Stable byte-order.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    sorted_comps = sorted(
        components, key=lambda c: (c.ecosystem, c.name.lower(), c.version)
    )
    comps_json: list[dict] = []
    for c in sorted_comps:
        entry: dict = {"type": "library", "name": c.name, "version": c.version}
        lic = _cdx_licenses(c.spdx)
        if lic is not None:
            entry["licenses"] = lic
        purl = _component_purl(c)
        if purl:
            entry["purl"] = purl
        if c.source_url and not c.source_url.startswith("pkg:"):
            entry["externalReferences"] = [
                {"type": "distribution", "url": c.source_url}
            ]
        comps_json.append(entry)
    bom = {
        "bomFormat": "CycloneDX",
        "specVersion": "1.5",
        "version": 1,
        "components": comps_json,
    }
    output_path.write_text(json.dumps(bom, indent=2) + "\n", encoding="utf-8")
    return output_path


def load_subtract_keys(sbom_path: Path) -> set[tuple[str, str]]:
    """Load a baseline CycloneDX SBOM and return its (name, version) set.

    Used by the licenses stage to subtract baseline components from
    generator output so NOTICES attributes only what's above the baseline.
    Components without name+version are skipped silently (syft sometimes
    emits operating-system entries with no version).
    """
    if not sbom_path.is_file():
        raise FileNotFoundError(sbom_path)
    doc = json.loads(sbom_path.read_text(encoding="utf-8"))
    keys: set[tuple[str, str]] = set()
    for c in doc.get("components", []) or []:
        name = c.get("name")
        version = c.get("version")
        if name and version is not None:
            keys.add((name, str(version)))
    logger.info(
        "Loaded %d (name, version) keys for subtraction from %s",
        len(keys),
        sbom_path.name,
    )
    return keys


def subtract_baseline(
    components: list[Component], baseline_keys: set[tuple[str, str]]
) -> list[Component]:
    """Drop components whose (name, version) appears in baseline_keys.

    Logs the count of dropped components so build logs make the
    subtraction visible — auditors and engineers can see exactly how
    many components NGC/baseline-owners are owning.
    """
    if not baseline_keys:
        return components

    # Some SBOM producers normalize Python names as hyphenated PEP 503 names
    # (e.g. vllm-test-utils) while dist-info METADATA can surface underscores
    # (e.g. vllm_test_utils). Keep exact matching as primary behavior, and add
    # a normalized fallback for separator-only differences.
    def _norm_name(name: str) -> str:
        return re.sub(r"[-_.]+", "-", name).lower()

    normalized_baseline_keys = {
        (_norm_name(name), version) for (name, version) in baseline_keys
    }

    kept: list[Component] = []
    dropped = 0
    for c in components:
        if (c.name, c.version) in baseline_keys or (
            _norm_name(c.name),
            c.version,
        ) in normalized_baseline_keys:
            dropped += 1
            continue
        kept.append(c)
    logger.info(
        "Subtracted %d baseline components; %d remain for NOTICES",
        dropped,
        len(kept),
    )
    return kept


def dedupe_by_name_version(components: list[Component]) -> list[Component]:
    """Collapse `(name, version)` duplicates. Keep the entry with the most
    license info: prefer non-UNKNOWN spdx, then license_text presence, then
    source_url presence.
    """
    by_key: dict[tuple[str, str], Component] = {}
    for c in components:
        key = (c.name, c.version)
        existing = by_key.get(key)
        if existing is None:
            by_key[key] = c
            continue
        if existing.spdx == UNKNOWN and c.spdx != UNKNOWN:
            by_key[key] = c
        elif existing.spdx == c.spdx and not existing.license_text and c.license_text:
            by_key[key] = c
    return list(by_key.values())
