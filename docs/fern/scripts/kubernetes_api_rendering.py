def _llms_only_markdown(reference: KubernetesReference) -> str:
    """Full Markdown twin of the compact page for agent-mode exports."""
    total_types = sum(len(pkg.types) for pkg in reference.packages)
    header = (
        f"Dynamo publishes {len(reference.packages)} Kubernetes API packages "
        f"with {total_types} typed CRD / config sections."
    )
    parts: list[str] = [header, ""]
    parts.extend(_llms_packages_summary(reference))
    for pkg in reference.packages:
        parts.append("")
        parts.extend(_llms_package_section(pkg))
    parts.append("")
    parts.append(
        f"Full raw Markdown (agent-friendly source): [`api-reference.md`]"
        f"({SOURCE_HREF_MD})"
    )
    return "\n".join(parts).rstrip() + "\n"


def _llms_packages_summary(reference: KubernetesReference) -> list[str]:
    """Compact table listing packages, type counts, and jump anchors."""
    rows = ["| Package | Types | Jump |", "| --- | --- | --- |"]
    for pkg in reference.packages:
        rows.append(
            f"| `{pkg.name}` | {len(pkg.types)} | [#{pkg.anchor}](#{pkg.anchor}) |"
        )
    return rows


def _llms_package_section(pkg: KubernetesPackage) -> list[str]:
    """Markdown block for one package (Resource Types + typed rows)."""
    valid_anchors = {type_.anchor for type_ in pkg.types}
    lines = [f'### {pkg.name} <a id="{pkg.anchor}"></a>']
    if pkg.description:
        lines += ["", pkg.description]
    if pkg.resource_types:
        lines += ["", "**Resource Types:**"]
        for ref in pkg.resource_types:
            lines.append(f"- [{ref.name}](#{ref.anchor})")
    lines.append("")
    lines.append("| Type | Kind | Summary |")
    lines.append("| --- | --- | --- |")
    for t in pkg.types:
        lines.append(_llms_type_row(t))
    for type_ in pkg.types:
        lines += ["", *_llms_type_section(type_, valid_anchors)]
    return lines


def _llms_type_row(type_: KubernetesType) -> str:
    """One row of the per-package Markdown type table."""
    summary = _first_line(type_.description)
    return (
        f"| [`{type_.display_name}`](#{type_.anchor}) | "
        f"{type_.kind} | {_md_cell(summary)} |"
    )


def _llms_type_section(type_: KubernetesType, valid_anchors: set[str]) -> list[str]:
    """Complete Markdown schema for one Kubernetes type."""
    lines = [f'#### {type_.display_name} <a id="{type_.anchor}"></a>']
    lines += ["", f"**Kind:** {type_.kind}"]
    if type_.description:
        lines += ["", type_.description]
    if type_.underlying_type:
        lines += ["", f"**Underlying type:** `{type_.underlying_type}`"]
    if type_.validation:
        lines += ["", f"**Validation:** {type_.validation}"]
    if type_.appears_in:
        refs = ", ".join(f"[{ref.name}](#{ref.anchor})" for ref in type_.appears_in)
        lines += ["", f"**Appears in:** {refs}"]
    if type_.fields:
        lines += ["", *_llms_field_table(type_.fields, valid_anchors)]
    if type_.enum_values:
        lines += ["", "**Enum values:**", *_llms_enum_list(type_.enum_values)]
    return lines


def _llms_field_table(
    fields: Iterable[KubernetesField], valid_anchors: set[str]
) -> list[str]:
    """Complete Markdown table for a type's fields."""
    lines = [
        "| Field | Type | Required | Default | Description | Validation |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for field in fields:
        field_type = _resolved_field_type(field.type, valid_anchors)
        lines.append(
            f"| `{field.name}` | {_md_cell(field_type)} | "
            f"{'yes' if field.required else 'no'} | {_md_cell(field.default)} | "
            f"{_md_cell(field.description)} | {_md_cell(field.validation)} |"
        )
    return lines


def _resolved_field_type(field_type: str, valid_anchors: set[str]) -> str:
    """Preserve valid local type links and unwrap unresolved ones."""
    return LOCAL_FRAGMENT_LINK_RE.sub(
        lambda match: (
            match.group(0)
            if match.group("anchor") in valid_anchors
            else match.group("label")
        ),
        field_type,
    )


def _llms_enum_list(values: Iterable[KubernetesEnumValue]) -> list[str]:
    """Markdown bullets for every enum value and its description."""
    return [f"- `{value.name}`: {value.description or '-'}" for value in values]


def _first_line(text: str) -> str:
    """First non-empty line of ``text`` (or an empty string)."""
    for line in text.splitlines():
        stripped = line.strip()
        if stripped:
            return stripped
    return ""


def _md_cell(text: str) -> str:
    """Sanitize a cell value for a Markdown table."""
    return escape_mdx_table_cell(text)


def _iter_all_types(
    reference: KubernetesReference,
) -> Iterable[KubernetesType]:
    """Convenience iterator over every type in the reference."""
    for pkg in reference.packages:
        yield from pkg.types


def _subsection_titles(subsections: Iterable[OperatorDefaultsSubsection]) -> list[str]:
    """Return the titles of every operator-defaults subsection in order."""
    return [sub.title for sub in subsections]


