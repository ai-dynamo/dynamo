"""Deterministic serialization for the Dynamo Kubernetes API reference.

Consumes the discovered :class:`~kubernetes_api_discovery.KubernetesReference`
model and produces:

* the typed TypeScript data module snapshotted beside the versioned page; and
* the thin MDX shell that mounts ``<ReferenceStyles />`` and
  ``<ApiKubernetesReference />``, embeds the twelve operator-default
  subsections as demoted Markdown headings, and carries a full
  ``<llms-only>`` Markdown twin so agent exports still see the 165-type
  surface after the compact React component is stripped.

No I/O happens in this module -- callers own the writes. Identical inputs
must produce byte-identical outputs so ``--check`` and diff review stay
reliable.
"""

from __future__ import annotations

import json
import re
from collections.abc import Callable, Iterable
from typing import Any

from kubernetes_api_discovery import (
    KubernetesEnumValue,
    KubernetesField,
    KubernetesPackage,
    KubernetesReference,
    KubernetesType,
    KubernetesTypeRef,
    OperatorDefaults,
    OperatorDefaultsSubsection,
)
from markdown_rendering import escape_mdx_table_cell

TS_GENERATED_MARKER = (
    "GENERATED by docs/fern/scripts/gen_kubernetes_api.py -- do not edit."
)
MDX_GENERATED_MARKER = (
    "{/* GENERATED by docs/fern/scripts/gen_kubernetes_api.py -- do not edit. */}"
)
LOCAL_FRAGMENT_LINK_RE = re.compile(r"\[(?P<label>[^\]]+)\]\(#(?P<anchor>[^)]+)\)")
SOURCE_HREF_MD = (
    "https://github.com/ai-dynamo/dynamo/blob/main/docs/fern/kubernetes/"
    "api-reference.md"
)


# ---------------------------------------------------------------------------
# TypeScript data module
# ---------------------------------------------------------------------------


def render_ts_data(reference: KubernetesReference) -> str:
    """Render the typed TS data module the React component consumes."""
    header = (
        "/*\n"
        " * SPDX-FileCopyrightText: Copyright (c) 2025-2026 NVIDIA "
        "CORPORATION & AFFILIATES. All rights reserved.\n"
        " * SPDX-License-Identifier: Apache-2.0\n"
        " *\n"
        f" * {TS_GENERATED_MARKER}\n"
        " *\n"
        " * The generator parses the upstream crd-ref-docs Markdown at\n"
        " * docs/fern/kubernetes/api-reference.md into a typed model. Edit\n"
        " * docs/fern/scripts/kubernetes_api_discovery.py or the upstream\n"
        " * Markdown source, then re-run gen_kubernetes_api.py; hand-editing\n"
        " * this file is not preserved.\n"
        " */\n"
    )
    body = (
        "\nimport type { KubernetesReference } from "
        '"@/components/KubernetesApiTypes";\n\n'
        f"{_ts_reference_literal(reference)}"
    )
    return header + body


def _ts_reference_literal(reference: KubernetesReference) -> str:
    """Render the ``export const KUBERNETES_REFERENCE`` object literal."""
    lines = [
        "export const KUBERNETES_REFERENCE: KubernetesReference = {",
        f"  sourceHref: {json.dumps(SOURCE_HREF_MD)},",
        "  packages: [",
    ]
    for package in reference.packages:
        lines.extend(_ts_package_lines(package))
    lines.append("  ],")
    lines.extend(_ts_operator_defaults_lines(reference.operator_defaults))
    lines.append("};\n")
    return "\n".join(lines)


def _ts_package_lines(package: KubernetesPackage) -> list[str]:
    """Render one ``KubernetesPackage`` object literal."""
    header = [
        "    {",
        f"      name: {json.dumps(package.name)},",
        f"      anchor: {json.dumps(package.anchor)},",
        f"      description: {json.dumps(package.description)},",
        "      resourceTypes: [",
    ]
    for ref in package.resource_types:
        header.append(_ts_typeref_inline(ref))
    header.append("      ],")
    header.append("      types: [")
    for type_ in package.types:
        header.extend(_ts_type_lines(type_))
    header.append("      ],")
    header.append("    },")
    return header


def _ts_typeref_inline(ref: KubernetesTypeRef) -> str:
    """Render one ``KubernetesTypeRef`` on a single line."""
    return (
        f"        {{ name: {json.dumps(ref.name)}, anchor: {json.dumps(ref.anchor)} }},"
    )


def _ts_type_lines(type_: KubernetesType) -> list[str]:
    """Render one ``KubernetesType`` object literal."""
    lines = _ts_type_header_lines(type_)
    lines.extend(_ts_array_block("appearsIn", type_.appears_in, _ts_typeref_deep))
    lines.extend(_ts_array_block("fields", type_.fields, _ts_field_line))
    lines.extend(_ts_array_block("enumValues", type_.enum_values, _ts_enum_value_line))
    lines.append("        },")
    return lines


def _ts_type_header_lines(type_: KubernetesType) -> list[str]:
    """Scalar prefix of a ``KubernetesType`` literal (before the arrays)."""
    return [
        "        {",
        f"          name: {json.dumps(type_.name)},",
        f"          displayName: {json.dumps(type_.display_name)},",
        f"          anchor: {json.dumps(type_.anchor)},",
        f"          kind: {json.dumps(type_.kind)},",
        f"          description: {json.dumps(type_.description)},",
        f"          underlyingType: {json.dumps(type_.underlying_type)},",
        f"          validation: {json.dumps(type_.validation)},",
    ]


def _ts_array_block(
    key: str, items: tuple[Any, ...], render: Callable[[Any], str]
) -> list[str]:
    """Render one ``key: [ <render(item)>... ],`` block on the type literal."""
    body = [f"          {key}: ["]
    for item in items:
        body.append(render(item))
    body.append("          ],")
    return body


def _ts_typeref_deep(ref: KubernetesTypeRef) -> str:
    """Render one ``KubernetesTypeRef`` inside a nested type array."""
    return (
        f"            {{ name: {json.dumps(ref.name)}, "
        f"anchor: {json.dumps(ref.anchor)} }},"
    )


def _ts_field_line(field: KubernetesField) -> str:
    """Render one ``KubernetesField`` object literal on a single line."""
    return (
        "            { "
        f"name: {json.dumps(field.name)}, "
        f"type: {json.dumps(field.type)}, "
        f"default: {json.dumps(field.default)}, "
        f"required: {json.dumps(field.required)}, "
        f"description: {json.dumps(field.description)}, "
        f"validation: {json.dumps(field.validation)}"
        " },"
    )


def _ts_enum_value_line(value: KubernetesEnumValue) -> str:
    """Render one ``KubernetesEnumValue`` object literal on a single line."""
    return (
        "            { "
        f"name: {json.dumps(value.name)}, "
        f"description: {json.dumps(value.description)}"
        " },"
    )


def _ts_operator_defaults_lines(defaults: OperatorDefaults) -> list[str]:
    """Render the ``operatorDefaults`` object literal (intro + subsections)."""
    lines = [
        "  operatorDefaults: {",
        f"    introMarkdown: {json.dumps(defaults.intro_markdown)},",
        "    subsections: [",
    ]
    for sub in defaults.subsections:
        lines.append(
            "      { "
            f"title: {json.dumps(sub.title)}, "
            f"anchor: {json.dumps(sub.anchor)}, "
            f"bodyMarkdown: {json.dumps(sub.body_markdown)}"
            " },"
        )
    lines.append("    ],")
    lines.append("  },")
    return lines


