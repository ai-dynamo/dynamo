class Block(NamedTuple):
    """One generated span in a page, delimited by ``<marker>:begin/:end``."""

    marker: str
    renderer: Callable[[dict], str]
    # Hide the body from human readers, leaving it only in agent exports.
    llms_only: bool
    # Append the span at end of file when the page has no markers yet.
    # False fails closed instead, so placement stays under human control.
    append_if_missing: bool


# The three component-backed pages get <llms-only> twins (humans see the React
# components); releases-machine-readable.mdx IS the page body, human-viewable
# and machine-consumable alike.
PAGES: dict[str, tuple[Block, ...]] = {
    "compatibility.mdx": (
        # The driver-floor table inverts the support matrix: read across from a
        # driver you already have to the newest release each backend can run on
        # it. <ReleaseSupportMatrix /> renders the forward view (release -> min
        # driver) and has no inverse mode, so this stays a generated span.
        Block("driver-floors", render_driver_floors, False, False),
        Block("llms-tables", render_compatibility, True, True),
    ),
    "release-artifacts.mdx": (
        Block("llms-tables", render_release_artifacts, True, True),
    ),
    "model-early-access-builds.mdx": (
        Block("llms-tables", render_model_ea_builds, True, True),
    ),
    "releases-machine-readable.mdx": (
        Block("llms-tables", render_releases_data, False, True),
    ),
    "releases/release-history.mdx": (
        Block("release-stats", render_release_stats, False, False),
    ),
}

# Scope to the support claim published in releases.json. Explicit rather than
# defaulting to "Supported": the rows have not always carried it -- the CentOS
# Stream row this PR removes was "Experimental" -- so a blanket default would
# publish a support claim for the next preview or restricted scope added here.
# Unmapped fails closed, like feature_cell and the interaction glyphs.
SCOPE_STATUS: dict[str, str] = {
    "Containers and wheels": "Supported",
    "Wheels only": "Supported",
}

# Standalone machine-readable outputs (path -> builder returning full text).
ASSET_OUTPUTS = {
    JSON_PATH: build_json,
    ATOM_PATH: build_atom,
}


def block_re(marker: str) -> re.Pattern[str]:
    """Match an existing generated span. Tolerant of edits to the note after
    "<marker>:begin" so a hand-tweaked marker comment is still replaced."""
    name = re.escape(marker)
    return re.compile(
        rf"\{{/\*\s*{name}:begin[^*]*\*/\}}.*?\{{/\*\s*{name}:end\s*\*/\}}",
        re.DOTALL,
    )


def build_block(block: Block, body: str) -> str:
    begin, end = marker_begin(block.marker), marker_end(block.marker)
    if block.llms_only:
        return f"{begin}\n<llms-only>\n\n{body}\n\n</llms-only>\n{end}"
    return f"{begin}\n\n{body}\n\n{end}"


def apply_block(page_text: str, block: Block, rendered: str) -> str:
    pattern = block_re(block.marker)
    if pattern.search(page_text):
        return pattern.sub(lambda _m: rendered, page_text, count=1)
    if not block.append_if_missing:
        raise TSParseError(
            f"{block.marker}: markers not found — the page must contain "
            f"{marker_begin(block.marker)} and {marker_end(block.marker)} "
            "where the generated span belongs"
        )
    # No markers yet: append at end of file, before the trailing newline.
    return page_text.rstrip("\n") + "\n\n" + rendered + "\n"


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if regeneration would change a marker-spliced page; write nothing",
    )
    mode.add_argument(
        "--assets-only",
        action="store_true",
        help="write only assets/releases.json and assets/releases-atom.xml",
    )
    args = ap.parse_args(argv)

    try:
        data = parse_data_module(DATA_TS)
    except TSParseError as exc:
        print(f"error: failed to parse {DATA_TS}: {exc}", file=sys.stderr)
        return 2

    # Render every selected output up front so a rendering failure emits nothing.
    try:
        rendered: dict[Path, str] = {}
        if not args.assets_only:
            for page_name, blocks in PAGES.items():
                page_path = REFERENCE_DIR / page_name
                if not page_path.is_file():
                    print(f"error: page not found: {page_path}", file=sys.stderr)
                    return 2
                text = page_path.read_text(encoding="utf-8")
                for block in blocks:
                    body = build_block(block, block.renderer(data))
                    text = apply_block(text, block, body)
                rendered[page_path] = text
        if not args.check:
            for asset_path, builder in ASSET_OUTPUTS.items():
                rendered[asset_path] = builder(data)
    except (TSParseError, KeyError) as exc:
        print(f"error: rendering failed: {exc!r}", file=sys.stderr)
        return 2

    stale = []
    for path, new_text in rendered.items():
        # Relative to the reference root so pages in subdirectories are
        # distinguishable -- several are named README.mdx.
        name = (
            str(path.relative_to(REFERENCE_DIR))
            if path.is_relative_to(REFERENCE_DIR)
            else path.name
        )
        # Compare and write raw bytes: read_text() would normalize CRLF away,
        # letting a wrongly-encoded output pass as "unchanged" (and --check
        # as fresh) without ever being healed.
        old_bytes = path.read_bytes() if path.is_file() else None
        new_bytes = new_text.encode("utf-8")
        if new_bytes == old_bytes:
            print(f"{name}: unchanged")
            continue
        stale.append(name)
        if args.check:
            print(f"{name}: STALE (regeneration would change it)")
        else:
            path.write_bytes(new_bytes)
            print(f"{name}: wrote {len(new_bytes)} bytes")

    if args.check and stale:
        print(
            f"check failed: {len(stale)} output(s) stale — run gen_llms_tables.py",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
