"""Regenerate the experimental client from Snapshot's public PageBroker proto.

Usage: python generate_pagebroker_bindings.py /snapshot/agent/pagebroker/v1/pagebroker.proto
Qualification used protoc 3.21.12; the exact API source is in pagebroker-gms-native.patch.
"""

import argparse
import hashlib
import subprocess
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("schema", type=Path)
args = parser.parse_args()
schema = args.schema.resolve(strict=True)
output = Path(__file__).resolve().parent
subprocess.run(
    ["protoc", "-I" + str(schema.parent), "--python_out=" + str(output), str(schema)],
    check=True,
)
generated = output / "pagebroker_pb2.py"
header = (
    "# SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES.\n"
    "# SPDX-License-Identifier: Apache-2.0\n"
    "# Generated by generate_pagebroker_bindings.py; do not edit.\n"
    f"# Source proto SHA256: {hashlib.sha256(schema.read_bytes()).hexdigest()}\n"
)
generated.write_text(header + generated.read_text())
